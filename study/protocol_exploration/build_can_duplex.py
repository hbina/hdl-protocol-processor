#!/usr/bin/env python3
"""Combine the RX and TX probes to measure one-image instruction capacity.

This is a capacity-only candidate, not a simulated bidirectional result. It
shares request handling and completion publication; protocol paths remain
generic instructions. RX uses operation1; TX uses operation2 and arguments
ID high/ID low/DLC, with payload in the input FIFO.
"""

import argparse
import re
from pathlib import Path

from build_can_rx import generate as receive_source
from build_can_tx import generate as transmit_source
from tools.isa import BASE, WIDE512, IsaError
from tools.isa import CMPI, JFAIL, JMP, LDI, LOAD, Label, PREAD, STORE, r0, r1, r2, r3
from tools.program import Comment, Program


SHARED_LABELS = {"idle", "failure", "publish", "event"}


def namespace(source: Program, prefix: str) -> Program:
    """Prefix every label the fragment defines, except the shared entry points."""

    defined = {label.name for label in source.labels()} - SHARED_LABELS

    def rename(label: Label) -> Label:
        return Label(prefix + label.name) if label.name in defined else label

    def rename_words(text: str) -> str:
        # Comments mention labels by name; later generations match on them.
        for label in sorted(defined, key=len, reverse=True):
            text = re.sub(rf"\b{label}\b", prefix + label, text)
        return text

    renamed = source.map_labels(rename)
    return Program(
        [
            Comment(rename_words(item.text)) if isinstance(item, Comment) else item
            for item in renamed
        ]
    )


def generate():
    rx = receive_source()
    tx = transmit_source()
    prefix, rx_body = rx.split([LDI(r1, 242)], 1)
    rx_body = [LDI(r1, 242)] + rx_body
    rx_body, footer = rx_body.split([Label("failure")], 1)
    tx_body = tx[tx.comment_index("Build unstuffed") :]
    tx_body = tx_body.split([Label("failure")], 1)[0]
    old = [LDI(r2, 14), Label("record")]
    assert prefix.count(old) == 1
    prefix = prefix.replace(
        old, [PREAD(r0, r3), LDI(r1, 250), STORE(r0, r1), LDI(r2, 13), Label("record")]
    )
    dispatch = [
        LDI(r1, 250),
        LOAD(r0, r1),
        CMPI(r0, 2),
        JFAIL(Label("rx_entry")),
        JMP(Label("tx_entry")),
    ]
    combined = (
        prefix
        + dispatch
        + [Label("rx_entry")]
        + namespace(rx_body, "rx_")
        + [JMP(Label("failure")), Label("tx_entry")]
        + namespace(tx_body, "tx_")
        + [Label("failure")]
        + footer
    )
    return (
        Program(
            [
                Comment(
                    "GENERATED by build_can_duplex.py. Capacity-only; not simulated."
                ),
                Comment(
                    "Operation1=RX,2=TX. Branch target encoding beyond512 is unresolved."
                ),
            ]
        )
        + combined
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-capacity", type=int, choices=[128, 512])
    args = parser.parse_args()
    source = generate()
    Path(__file__).with_name("can_duplex_candidate.asm").write_text(source.to_asm())
    # Count instructions without pretending the ISA can encode >512 words.
    words = source.size
    if args.check_capacity:
        try:
            source.link(BASE if args.check_capacity == 128 else WIDE512)
        except IsaError as error:
            parser.exit(1, f"Combined CAN capacity: {error}\n")
        parser.exit(0, "Capacity now fits; the candidate still requires simulation\n")
    print(f"Combined CAN candidate: {words} words; capacity-only, not simulated.")


if __name__ == "__main__":
    main()
