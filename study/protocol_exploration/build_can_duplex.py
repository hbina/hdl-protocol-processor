#!/usr/bin/env python3
"""Combine the RX and TX probes to measure one-image instruction capacity.

This is a capacity-only candidate, not a simulated bidirectional result. It
shares request handling and completion publication; protocol paths remain
generic instructions. RX uses operation1; TX uses operation2 and arguments
ID high/ID low/DLC, with payload in the input FIFO.
"""

import argparse
import re
from pathlib import Path

from build_can_rx import generate as receive_source
from build_can_tx import generate as transmit_source
from run_can import study_assembler

from tools.assembler import AssemblyError, assemble


def namespace(source, prefix):
    labels = re.findall(r"^([A-Za-z_][A-Za-z_0-9]*):", source, re.MULTILINE)
    for label in sorted(labels, key=len, reverse=True):
        if label not in {"idle", "failure", "publish", "event"}:
            source = re.sub(rf"\b{label}\b", prefix + label, source)
    return source


def generate():
    rx = receive_source()
    tx = transmit_source()
    prefix, rx_body = rx.split("LDI r1, 242\n", 1)
    rx_body = "LDI r1, 242\n" + rx_body
    rx_body, footer = rx_body.split("\nfailure:\n", 1)
    tx_body = tx.split("# Build unstuffed", 1)[1].split("\nfailure:\n", 1)[0]
    tx_body = "# Build unstuffed" + tx_body
    old = "LDI r2, 14\nrecord:"
    assert prefix.count(old) == 1
    prefix = prefix.replace(
        old, "PREAD r0, r3\nLDI r1, 250\nSTORE r0, r1\nLDI r2, 13\nrecord:"
    )
    dispatch = "LDI r1, 250\nLOAD r0, r1\nCMPI r0, 2\nJFAIL rx_entry\nJMP tx_entry\n"
    combined = (
        prefix
        + dispatch
        + "rx_entry:\n"
        + namespace(rx_body, "rx_")
        + "\nJMP failure\ntx_entry:\n"
        + namespace(tx_body, "tx_")
        + "\nfailure:\n"
        + footer
    )
    return (
        "# GENERATED by build_can_duplex.py. Capacity-only; not simulated.\n"
        "# Operation1=RX,2=TX. Branch target encoding beyond512 is unresolved.\n"
        + combined
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-capacity", type=int, choices=[128, 512])
    args = parser.parse_args()
    source = generate()
    Path(__file__).with_name("can_duplex_candidate.asm").write_text(source)
    # Count instructions without pretending the ISA can encode >512 words.
    words = sum(
        bool(line.strip()) and not line.startswith("#") and not line.endswith(":")
        for line in source.splitlines()
    )
    if args.check_capacity:
        model = study_assembler()
        try:
            (assemble if args.check_capacity == 128 else model.assemble)(source)
        except (AssemblyError, model.AssemblyError) as error:
            parser.exit(1, f"Combined CAN capacity: {error}\n")
        parser.exit(0, "Capacity now fits; the candidate still requires simulation\n")
    print(f"Combined CAN candidate: {words} words; capacity-only, not simulated.")


if __name__ == "__main__":
    main()
