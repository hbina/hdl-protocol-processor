#!/usr/bin/env python3
"""Correct the passive flag's equal-polarity wait with a bounded generic loop."""

from pathlib import Path

from build_can_fault import generate as fixed_flag_source


def generate():
    source = fixed_flag_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    passive = """LDI r1, 251
LOAD r0, r1
ANDI r0, 128
LDI r1, 250
LOAD r1, r1
ANDI r1, 128
OR r0, r1"""
    replace(
        """LDI r1, 251
LOAD r0, r1
ANDI r0, 128
MOV r7, r0
LDI r1, 250
LOAD r0, r1
ANDI r0, 128
OR r7, r0""",
        "CALL passive_state\nMOV r7, r0",
    )
    assert source.count(passive) == 2
    source = source.replace(passive, "CALL passive_state")
    # The shared leaf costs2 clocks more than the old inline flag-state check.
    replace("JZ r7, active_flag_start\nWAIT 66", "JZ r7, active_flag_start\nWAIT 64")
    replace("active_flag_start:\nWAIT 66", "active_flag_start:\nWAIT 64")
    replace(
        "flag_started:\nLDI r3, 6\nWAIT 255\nWAIT 40",
        """flag_started:
LDI r3, 6
LDI r1, 1
ORI r7, 64
WAIT 255
WAIT 38""",
    )
    replace(
        """flag_sample:
INBIT r0, 1
ANDI r0, 1
XORI r0, 1
OR r4, r0
DJNZ r3, flag_more
WAIT 94""",
        """flag_sample:
INBIT r0, 1
ANDI r0, 1
XOR r1, r0
JZ r1, flag_same_polarity
LDI r3, 6
JMP flag_polarity_ready
flag_same_polarity:
NOP
NOP
flag_polarity_ready:
MOV r1, r0
XORI r0, 1
OR r4, r0
ADDI r7, 255
MOV r0, r7
ANDI r0, 127
JZ r0, recovery_timeout
DJNZ r3, flag_more
WAIT 85""",
    )
    replace("flag_more:\nWAIT 255\nWAIT 137", "flag_more:\nWAIT 255\nWAIT 128")
    replace("flag_finished:\nCMPI r2, 21", "flag_finished:\nANDI r7, 128\nCMPI r2, 21")
    replace(
        "LDI r2, 8\nLDI r3, 32\nWAIT 255\nWAIT 4\nJMP error_delimiter_sample",
        "LDI r2, 8\nLDI r3, 32\nWAIT 255\nWAIT 3\nJMP error_delimiter_sample",
    )
    return (source + "passive_state:\n" + passive + "\nRET\n").replace(
        "# GENERATED by build_can_fault.py.",
        "# GENERATED by build_can_fault_equal.py. Six equal bits;64-sample flag limit.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_fault_equal_candidate.asm").write_text(generate())
