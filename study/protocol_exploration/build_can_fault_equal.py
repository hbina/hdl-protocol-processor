#!/usr/bin/env python3
"""Correct the passive flag's equal-polarity wait with a bounded generic loop."""

from pathlib import Path

from build_can_fault import generate as fixed_flag_source
from tools.isa import (
    ADDI,
    ANDI,
    CALL,
    CMPI,
    DJNZ,
    INBIT,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    MOV,
    NOP,
    OR,
    ORI,
    RET,
    WAIT,
    XOR,
    XORI,
    r0,
    r1,
    r2,
    r3,
    r4,
    r7,
)


def generate():
    source = fixed_flag_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    passive = [
        LDI(r1, 251),
        LOAD(r0, r1),
        ANDI(r0, 128),
        LDI(r1, 250),
        LOAD(r1, r1),
        ANDI(r1, 128),
        OR(r0, r1),
    ]
    replace(
        [
            LDI(r1, 251),
            LOAD(r0, r1),
            ANDI(r0, 128),
            MOV(r7, r0),
            LDI(r1, 250),
            LOAD(r0, r1),
            ANDI(r0, 128),
            OR(r7, r0),
        ],
        [CALL(Label("passive_state")), MOV(r7, r0)],
    )
    assert source.count(passive) == 2
    source = source.replace(passive, [CALL(Label("passive_state"))])
    # The shared leaf costs2 clocks more than the old inline flag-state check.
    replace(
        [JZ(r7, Label("active_flag_start")), WAIT(66)],
        [JZ(r7, Label("active_flag_start")), WAIT(64)],
    )
    replace(
        [Label("active_flag_start"), WAIT(66)], [Label("active_flag_start"), WAIT(64)]
    )
    replace(
        [Label("flag_started"), LDI(r3, 6), WAIT(255), WAIT(40)],
        [
            Label("flag_started"),
            LDI(r3, 6),
            LDI(r1, 1),
            ORI(r7, 64),
            WAIT(255),
            WAIT(38),
        ],
    )
    replace(
        [
            Label("flag_sample"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            XORI(r0, 1),
            OR(r4, r0),
            DJNZ(r3, Label("flag_more")),
            WAIT(94),
        ],
        [
            Label("flag_sample"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            XOR(r1, r0),
            JZ(r1, Label("flag_same_polarity")),
            LDI(r3, 6),
            JMP(Label("flag_polarity_ready")),
            Label("flag_same_polarity"),
            NOP(),
            NOP(),
            Label("flag_polarity_ready"),
            MOV(r1, r0),
            XORI(r0, 1),
            OR(r4, r0),
            ADDI(r7, 255),
            MOV(r0, r7),
            ANDI(r0, 127),
            JZ(r0, Label("recovery_timeout")),
            DJNZ(r3, Label("flag_more")),
            WAIT(85),
        ],
    )
    replace(
        [Label("flag_more"), WAIT(255), WAIT(137)],
        [Label("flag_more"), WAIT(255), WAIT(128)],
    )
    replace(
        [Label("flag_finished"), CMPI(r2, 21)],
        [Label("flag_finished"), ANDI(r7, 128), CMPI(r2, 21)],
    )
    replace(
        [
            LDI(r2, 8),
            LDI(r3, 32),
            WAIT(255),
            WAIT(4),
            JMP(Label("error_delimiter_sample")),
        ],
        [
            LDI(r2, 8),
            LDI(r3, 32),
            WAIT(255),
            WAIT(3),
            JMP(Label("error_delimiter_sample")),
        ],
    )
    return (source + [Label("passive_state")] + passive + [RET()]).replace_comment_text(
        "GENERATED by build_can_fault.py.",
        "GENERATED by build_can_fault_equal.py. Six equal bits;64-sample flag limit.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_fault_equal_candidate.asm").write_text(
        generate().to_asm()
    )
