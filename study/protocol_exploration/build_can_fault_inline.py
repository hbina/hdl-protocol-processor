#!/usr/bin/env python3
"""Preserved larger CAN firmware comparison with both generic leaves inlined."""

from pathlib import Path

from build_can_duplex import namespace
from build_can_fault import generate as fault_source
from tools.isa import CALL, RET, Call, Label, Ret


def generate():
    prefix, leaves = fault_source().split([Label("emit_byte")])
    emit, increment = leaves.split([Label("increment_tec")])
    emit = emit.removesuffix([RET()])
    increment = increment.removesuffix([RET()])
    source = prefix.replace([CALL(Label("emit_byte"))], emit)
    copies = 0
    while [CALL(Label("increment_tec"))] in source:
        copies += 1
        source = source.replace(
            [CALL(Label("increment_tec"))], namespace(increment, f"inline_{copies}_"), 1
        )
    assert copies > 0 and not any(isinstance(item, (Call, Ret)) for item in source)
    return source.replace_comment_text(
        "GENERATED by build_can_fault.py.",
        "GENERATED by build_can_fault_inline.py. No CALL/RET.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_fault_inline_candidate.asm").write_text(
        generate().to_asm()
    )
