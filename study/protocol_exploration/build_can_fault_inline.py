#!/usr/bin/env python3
"""Preserved larger CAN firmware comparison with both generic leaves inlined."""

from pathlib import Path

from build_can_duplex import namespace
from build_can_fault import generate as fault_source


def generate():
    prefix, leaves = fault_source().split("\nemit_byte:\n")
    emit, increment = leaves.split("\nincrement_tec:\n")
    emit = emit.rstrip().removesuffix("RET").rstrip() + "\n"
    increment = increment.rstrip().removesuffix("RET").rstrip() + "\n"
    source = prefix.replace("CALL emit_byte", emit.rstrip())
    copies = 0
    while "CALL increment_tec" in source:
        copies += 1
        source = source.replace(
            "CALL increment_tec", namespace(increment, f"inline_{copies}_").rstrip(), 1
        )
    assert copies > 0 and "CALL " not in source and "\nRET" not in source
    return (
        source.replace(
            "# GENERATED by build_can_fault.py.",
            "# GENERATED by build_can_fault_inline.py. No CALL/RET.",
        )
        + "\n"
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_fault_inline_candidate.asm").write_text(generate())
