#!/usr/bin/env python3
"""Draft active error-flag bit-error restart/accounting using the generic ISA.

This first integration intentionally preserves the full listing even if real
1024-word assembly rejects it. It is not behavior-verified until it assembles
and passes the independent fault peer and earlier protocol regressions.
"""

from pathlib import Path

from build_can_postflag import generate as prior_source


def generate():
    source = prior_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    begin = source.index("flag_finished:\n")
    end = source.index("LDI r4, 0\nLDI r2, 8\n", begin)
    charge = source[begin:end].removeprefix("flag_finished:\nANDI r7, 128\n")
    # Account for the original error before sampling the flag, so a later
    # flag-bit error sees the updated error-active/passive threshold state.
    # Passive ACK with no observed dominant bit is deferred until completion.
    charge = charge.replace(
        "balance_109_yes:\nWAIT 16", "balance_109_yes:\nLDI r4, 2\nWAIT 15"
    )
    source = (
        source[:begin]
        + """flag_finished:
CMPI r4, 3
JFAIL flagbit_no_deferred_ack
CALL increment_tec
JMP flagbit_deferred_done
flagbit_no_deferred_ack:
WAIT 16
flagbit_deferred_done:
"""
        + source[end:]
    )
    replace(
        "flag_started:\nLDI r3, 6\nORI r7, 64\nWAIT 255\nWAIT 39",
        "flag_started:\nLDI r3, 6\n"
        + charge
        + "ORI r7, 64\nLDI r1, 1\nWAIT 255\nWAIT 2",
    )
    replace(
        "flag_sample:\nINBIT r0, 1\nANDI r0, 1\nXOR r1, r0",
        """flag_sample:
INBIT r0, 1
ANDI r0, 1
CMPLTI r7, 128
JFAIL flagbit_passive_sample
JZ r0, flagbit_normal_sample
JMP flagbit_error
flagbit_passive_sample:
NOP
flagbit_normal_sample:
XOR r1, r0""",
    )
    replace("DJNZ r3, flag_more\nWAIT 85", "DJNZ r3, flag_more\nWAIT 82")
    replace("flag_more:\nWAIT 255\nWAIT 128", "flag_more:\nWAIT 255\nWAIT 125")
    # The final counter block changed its cost; preserve the intended next
    # sample phase. These pads remain draft until a runnable image is tested.
    replace(
        "LDI r3, 32\nWAIT 255\nNOP\nJMP error_delimiter_sample",
        "LDI r3, 32\nWAIT 255\nWAIT 18\nJMP error_delimiter_sample",
    )
    source += """
# 252 is dead transmit-packer scratch after an exchange abort. Save only the
# current flag sample budget; the leaf calls clobber r0/r1 and return_pc.
# No nested calls and no added data memory or protocol-specific operation.
flagbit_error:
LDI r1, 252
STORE r7, r1
CALL passive_state
CMPI r6, 6
JFAIL flagbit_transmit_increment
CALL increment_rec_eight
WAIT 4
JMP flagbit_incremented
flagbit_transmit_increment:
CALL increment_tec
NOP
flagbit_incremented:
LDI r1, 252
LOAD r1, r1
OR r7, r1
LDI r3, 6
MOV r0, r7
ANDI r0, 128
LDI r1, 1
ADDI r7, 255
MOV r0, r7
ANDI r0, 127
JZ r0, recovery_timeout
MOV r0, r7
ANDI r0, 128
WAIT 45
JZ r0, flagbit_restart_active
SETO 1
JMP flagbit_restarted
flagbit_restart_active:
SETO 0
NOP
flagbit_restarted:
WAIT 255
WAIT 40
JMP flag_sample
increment_rec_eight:
LDI r1, 250
LOAD r0, r1
CMPLTI r0, 248
JFAIL flagbit_rec_saturates
ADDI r0, 8
JMP flagbit_rec_store
flagbit_rec_saturates:
LDI r0, 255
NOP
flagbit_rec_store:
STORE r0, r1
RET
"""
    return source.replace(
        "# GENERATED by build_can_postflag.py.",
        "# GENERATED by build_can_flag_bit.py. UNVERIFIED first integration; actual assembly capacity must be checked.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_flag_bit_candidate.asm").write_text(generate())
