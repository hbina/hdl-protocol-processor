#!/usr/bin/env python3
"""Compact the retained active-flag fault draft using generic software reuse."""

from pathlib import Path

from build_can_flag_bit import generate as draft_source


def generate():
    source = draft_source()

    def replace(old, new, count=1):
        nonlocal source
        assert source.count(old) == count, (old, source.count(old))
        source = source.replace(old, new)

    clear = "LDI r1, 250\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 251\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 255\nLDI r0, 0\nSTORE r0, r1\n"
    replace(clear, "CALL clear_counters\n", 2)
    source += (
        "clear_counters:\n"
        + clear.replace("LDI r1, 251\nLDI r0, 0", "LDI r1, 251").replace(
            "LDI r1, 255\nLDI r0, 0", "LDI r1, 255"
        )
        + "RET\n"
    )
    common = "LDI r1, 242\nLDI r0, 1\nSTORE r0, r1\nLDI r1, 243\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 245\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 247\nLDI r0, 144\nSTORE r0, r1\n"
    # Initial receive setup is off-wire, so move its header count after the
    # common stores to expose the same leaf as initial TX and retransmission.
    replace(
        "LDI r1, 243\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 244\nLDI r0, 19\nSTORE r0, r1\nLDI r1, 245",
        "LDI r1, 243\nLDI r0, 0\nSTORE r0, r1\nLDI r1, 245",
    )
    replace(
        "rx_entry:\n" + common,
        "rx_entry:\n" + common + "LDI r1, 244\nLDI r0, 19\nSTORE r0, r1\n",
    )
    replace(common, "CALL reset_frame_state\n", 3)
    source += (
        "reset_frame_state:\n"
        + common.replace("LDI r1, 245\nLDI r0, 0", "LDI r1, 245")
        + "RET\n"
    )
    replace("SHL r0\n" * 5 + "LDI r2, 3", "ROR r0\n" * 3 + "LDI r2, 3")
    # Offline CRC construction has no on-wire deadline; discard branch padding.
    replace(
        "XORI r3, 0x45\nJMP tx_balance_101_end\ntx_balance_101_yes:\nWAIT 2\ntx_balance_101_end:",
        "XORI r3, 0x45\ntx_balance_101_yes:\ntx_balance_101_end:",
    )
    # Two calculations are dead before the same scratch value is overwritten.
    replace("LDI r3, 6\nMOV r0, r7\nANDI r0, 128\nLDI r1, 1", "LDI r3, 6\nLDI r1, 1")
    replace(
        "WAIT 45\nJZ r0, flagbit_restart_active",
        "WAIT 47\nJZ r0, flagbit_restart_active",
    )
    replace(
        "LDI r7, 8\npostflag_receiver_add:\nCALL increment_rec_leaf\nDJNZ r7, postflag_receiver_add",
        "CALL increment_rec_eight\nWAIT 77",
    )
    begin = source.index("CMPI r6, 6\n", source.index("flag_started:\n"))
    end = source.index("ORI r7, 64\n", begin)
    source = (
        source[:begin]
        + """CMPI r6, 6
JFAIL flagbit_initial_transmit
CALL increment_rec_leaf
WAIT 22
JMP flagbit_initial_done
flagbit_initial_transmit:
CMPI r2, 21
JFAIL flagbit_initial_ack
LDI r1, 244
LOAD r0, r1
JZ r0, flagbit_initial_early
LDI r1, 246
LOAD r0, r1
JZ r0, flagbit_initial_middle
LDI r1, 247
LOAD r0, r1
CMPLTI r0, 157
JFAIL flagbit_initial_late
WAIT 17
JMP flagbit_initial_done
flagbit_initial_early:
WAIT 3
flagbit_initial_middle:
WAIT 4
flagbit_initial_late:
WAIT 1
flagbit_initial_charge:
CALL increment_tec
JMP flagbit_initial_done
flagbit_initial_ack:
JZ r7, flagbit_initial_ack_active
LDI r4, 2
WAIT 28
JMP flagbit_initial_done
flagbit_initial_ack_active:
WAIT 12
JMP flagbit_initial_charge
flagbit_initial_done:
"""
        + source[end:]
    )
    # Both initial roles qualify the same11-bit idle interval before their
    # role-specific next action. The new leaf adds only call/return clocks
    # outside a frame; all sampling loops retain their original400 clocks.
    idle = "LDI r2, 11\nLDI r3, 0\n{role}_idle_bus:\nINBIT r0, 1\nANDI r0, 1\nJZ r0, {role}_busy_bus\nWAIT 255\nWAIT 139\nDJNZ r2, {role}_idle_bus\n"
    busy = "{role}_busy_bus:\nLDI r2, 11\nDJNZ r3, {role}_idle_bus\nLDI r2, 6\nJMP failure\n"
    for role in ["rx", "tx"]:
        replace(idle.format(role=role), "CALL qualify_idle\n")
        replace(busy.format(role=role), "")
    source += (
        "qualify_idle:\n"
        + idle.format(role="shared")
        + "RET\n"
        + busy.format(role="shared")
    )
    return source.replace(
        "# GENERATED by build_can_flag_bit.py. UNVERIFIED first integration; actual assembly capacity must be checked.",
        "# GENERATED by build_can_flag_compact.py. Active flag-bit counter/restart experiment; generic software compaction.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_flag_compact_candidate.asm").write_text(generate())
