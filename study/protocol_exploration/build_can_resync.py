#!/usr/bin/env python3
"""Bounded CAN RX falling-edge phase correction in ordinary generic firmware."""

from pathlib import Path

from fragments import Fragment
from build_can_winner import generate as winner_source
from tools.isa import (
    ANDI,
    DJNZ,
    INBIT,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    MOV,
    SETO,
    WAIT,
    r0,
    r1,
    r2,
    r3,
    r4,
    r7,
)
from tools.program import Comment


def generate():
    source = winner_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    replace(
        [Label("rx_sof_seen"), LDI(r2, 0), LDI(r3, 0), WAIT(255), WAIT(36)],
        [Label("rx_sof_seen"), LDI(r2, 0), LDI(r3, 0), WAIT(192)],
    )
    # 143 balanced processing clocks precede this. A previous dominant sample
    # cannot qualify a recessive->dominant resynchronization edge. Poll only
    # after a recessive sample, once every4 clocks, at offsets148..252.
    phase = Fragment(
        [
            Label("rx_sample_ok"),
            LDI(r1, 246),
            LOAD(r4, r1),
            JZ(r4, Label("rx_no_edge_window")),
            LDI(r7, 27),
            Label("rx_edge_poll"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("rx_edge_seen")),
            DJNZ(r7, Label("rx_edge_poll")),
        ]
    )
    phase.add(Fragment.delay(143)).add(
        [JMP(Label("rx_sample")), Label("rx_no_edge_window")]
    )
    phase.add(Fragment.delay(252)).add([JMP(Label("rx_sample")), Label("rx_edge_seen")])
    # Detection consumes3 clocks; target next sample200 clocks after INBIT.
    phase.add(Fragment.delay(196)).add([JMP(Label("rx_sample"))])
    replace(
        [Label("rx_sample_ok"), WAIT(255), JMP(Label("rx_sample"))], (phase.program)
    )
    # Move CRC-delimiter/ACK/tail timing from75% to50%, preserving bit cells.
    replace(
        [
            Comment(
                "Drive ACK within its bit cell; exact phase checked by independent peer."
            ),
            WAIT(81),
            SETO(0),
            WAIT(255),
            WAIT(42),
        ],
        [
            Comment("50% sample: ACK starts200 clocks after CRC-delimiter sample."),
            WAIT(181),
            SETO(0),
            WAIT(198),
        ],
    )
    replace(
        [Label("rx_ack_ok"), WAIT(96), SETO(1), WAIT(255), WAIT(41)],
        [Label("rx_ack_ok"), WAIT(196), SETO(1), WAIT(197)],
    )
    # The winning frame's next RX sample moves from75% to50%. TX itself
    # retains75% sampling and a fixed nominal clock in this experiment.
    marker = [MOV(r2, r4), MOV(r3, r7), WAIT(255), WAIT(86), JMP(Label("rx_sample"))]
    replace(marker, [MOV(r2, r4), MOV(r3, r7), WAIT(242), JMP(Label("rx_sample"))])
    return source.replace_comment_text(
        "GENERATED by build_can_winner.py.",
        "GENERATED by build_can_resync.py. Bounded RX phase correction.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_resync_candidate.asm").write_text(generate().to_asm())
