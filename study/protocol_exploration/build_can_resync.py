#!/usr/bin/env python3
"""Bounded CAN RX falling-edge phase correction in ordinary generic firmware."""

from pathlib import Path

from build_can_rx import Block
from build_can_winner import generate as winner_source


def generate():
    source = winner_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    replace(
        "rx_sof_seen:\nLDI r2, 0\nLDI r3, 0\nWAIT 255\nWAIT 36",
        "rx_sof_seen:\nLDI r2, 0\nLDI r3, 0\nWAIT 192",
    )
    # 143 balanced processing clocks precede this. A previous dominant sample
    # cannot qualify a recessive->dominant resynchronization edge. Poll only
    # after a recessive sample, once every4 clocks, at offsets148..252.
    phase = Block("""rx_sample_ok:
LDI r1, 246
LOAD r4, r1
JZ r4, rx_no_edge_window
LDI r7, 27
rx_edge_poll:
INBIT r0, 1
ANDI r0, 1
JZ r0, rx_edge_seen
DJNZ r7, rx_edge_poll""")
    phase.add(Block.delay(143)).add("JMP rx_sample\nrx_no_edge_window:")
    phase.add(Block.delay(252)).add("JMP rx_sample\nrx_edge_seen:")
    # Detection consumes3 clocks; target next sample200 clocks after INBIT.
    phase.add(Block.delay(196)).add("JMP rx_sample")
    replace("rx_sample_ok:\nWAIT 255\nJMP rx_sample", "\n".join(phase.lines))
    # Move CRC-delimiter/ACK/tail timing from75% to50%, preserving bit cells.
    replace(
        """# Drive ACK within its bit cell; exact phase checked by independent peer.
WAIT 81
SETO 0
WAIT 255
WAIT 42""",
        """#50% sample: ACK starts200 clocks after CRC-delimiter sample.
WAIT 181
SETO 0
WAIT 198""",
    )
    replace(
        "rx_ack_ok:\nWAIT 96\nSETO 1\nWAIT 255\nWAIT 41",
        "rx_ack_ok:\nWAIT 196\nSETO 1\nWAIT 197",
    )
    # The winning frame's next RX sample moves from75% to50%. TX itself
    # retains75% sampling and a fixed nominal clock in this experiment.
    marker = "MOV r2, r4\nMOV r3, r7\nWAIT 255\nWAIT 86\nJMP rx_sample"
    replace(marker, "MOV r2, r4\nMOV r3, r7\nWAIT 242\nJMP rx_sample")
    return source.replace(
        "# GENERATED by build_can_winner.py.",
        "# GENERATED by build_can_resync.py. Bounded RX phase correction.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_resync_candidate.asm").write_text(generate())
