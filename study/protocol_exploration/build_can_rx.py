#!/usr/bin/env python3
"""Generate cycle-balanced generic-ISA CAN receive firmware, not an RTL engine.

Typed fragments balance conditional paths with ordinary WAIT/NOP
instructions. Runtime protocol work remains visible in can_candidate.asm.
"""

from pathlib import Path

from fragments import Fragment, load, put
from tools.isa import (
    ADDI,
    ANDI,
    CMPI,
    CMPLTI,
    DJNZ,
    INBIT,
    JFAIL,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    MOV,
    OR,
    PREAD,
    PWRITE,
    ROL,
    SETO,
    SETOE,
    SHL,
    STORE,
    WAIT,
    XOR,
    XORI,
    r0,
    r1,
    r2,
    r3,
)
from tools.program import Comment


def generate():
    Fragment.serial = 0
    out = Fragment(
        [
            Comment(
                "GENERATED by build_can_rx.py. Generic instructions only; RX milestone."
            ),
            Comment(
                "CAN transceiver TXD=uio0 (1 recessive), RXD=uio1. 125 kbit/s at50MHz."
            ),
            Comment(
                "Event128..143; unstuffed bits144..241; state242..249. Valid RX envelope."
            ),
            Comment("Header19 bits, data0..64 bits, CRC15. r2/r3 hold CRC low/high."),
            SETO(1),
            SETOE(1),
            Label("idle"),
            LDI(r3, 0x22),
            PREAD(r0, r3),
            JFAIL(Label("idle")),
            LDI(r1, 128),
            STORE(r0, r1),
            PREAD(r0, r3),
            ADDI(r1, 1),
            STORE(r0, r1),
            LDI(r2, 14),
            Label("record"),
            PREAD(r0, r3),
            DJNZ(r2, Label("record")),
            LDI(r1, 130),
            LDI(r0, 1),
            STORE(r0, r1),
            ADDI(r1, 1),
            LDI(r2, 13),
            LDI(r0, 0),
            Label("clear_event"),
            STORE(r0, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label("clear_event")),
            LDI(r3, 2),
            PREAD(r0, r3),
            LDI(r1, 132),
            STORE(r0, r1),
        ]
    )
    for address, value in [
        (242, 1),
        (243, 0),
        (244, 19),
        (245, 0),
        (247, 144),
        (248, 0),
    ]:
        out.add(put(address, value))
    out.add(
        [
            Comment(
                "Require 11 consecutive recessive bit times before arming SOF detection."
            ),
            LDI(r2, 11),
            LDI(r3, 0),
            Label("idle_bus"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("busy_bus")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("idle_bus")),
            LDI(r2, 0),
            LDI(r3, 0),
            Label("sof_wait"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("sof_seen")),
            DJNZ(r3, Label("sof_wait")),
            DJNZ(r2, Label("sof_wait")),
            LDI(r2, 6),
            JMP(Label("failure")),
            Label("busy_bus"),
            LDI(r2, 11),
            DJNZ(r3, Label("idle_bus")),
            LDI(r2, 6),
            JMP(Label("failure")),
            Label("sof_seen"),
            LDI(r2, 0),
            LDI(r3, 0),
            WAIT(255),
            WAIT(36),
            Label("sample"),
        ]
    )
    # Each nonterminal path from sample to sample is exactly400 core clocks.
    sample = Fragment([INBIT(r0, 1), ANDI(r0, 1), LDI(r1, 246), STORE(r0, r1)])
    stuff = load(242, r1).add([XOR(r1, r0)])
    stuff.add(Fragment.choose(lambda t: JZ(r1, t), put(248, 19)))
    stuff.add(load(246)).add([LDI(r1, 242), STORE(r0, r1)]).add(put(243, 1))

    logical = load(242, r1).add([XOR(r1, r0)])
    same = load(243).add([ADDI(r0, 1), STORE(r0, r1)])
    changed = load(246).add([LDI(r1, 242), STORE(r0, r1)]).add(put(243, 1))
    logical.add(Fragment.choose(lambda t: JZ(r1, t), same, changed))
    logical.add(load(246)).add(load(247, r1))
    logical.add(
        [
            STORE(r0, r1),
            ADDI(r1, 1),
            MOV(r0, r1),
            LDI(r1, 247),
            STORE(r0, r1),
            Comment(
                "CRC15, polynomial0x4599. Process received CRC too: valid residue is0."
            ),
            MOV(r0, r3),
            ANDI(r0, 64),
            LDI(r1, 246),
            LOAD(r1, r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            XOR(r0, r1),
            SHL(r3),
            ANDI(r3, 127),
            ROL(r2),
            MOV(r1, r2),
            ANDI(r1, 1),
            OR(r3, r1),
            ANDI(r2, 254),
        ]
    )
    logical.add(
        Fragment.choose(lambda t: JZ(r0, t), (), [XORI(r2, 0x99), XORI(r3, 0x45)])
    )
    logical.add(load(244)).add([ADDI(r0, 255), STORE(r0, r1)])
    header = Fragment(
        [
            Comment(
                "Only standard data frames: RTR/IDE/r0 must all be0 in this milestone."
            ),
            LDI(r1, 156),
            LOAD(r0, r1),
            ADDI(r1, 1),
            LOAD(r1, r1),
            OR(r0, r1),
            LDI(r1, 158),
            LOAD(r1, r1),
            OR(r0, r1),
        ]
    )
    header.add(Fragment.choose(lambda t: JZ(r0, t), (), put(248, 18)))
    header.add([LDI(r0, 0)])
    for address in range(159, 163):
        header.add([LDI(r1, address), LOAD(r1, r1), SHL(r0), OR(r0, r1)])
    header.add([LDI(r1, 249), STORE(r0, r1), CMPLTI(r0, 9)])
    header.add(Fragment.choose(JFAIL, put(248, 18)))
    header.add(load(249)).add(
        [SHL(r0), SHL(r0), SHL(r0), ADDI(r0, 15), LDI(r1, 244), STORE(r0, r1)]
    )
    header.add(put(245, 1))
    complete = put(245, 2).add([MOV(r0, r2), OR(r0, r3)])
    complete.add(Fragment.choose(lambda t: JZ(r0, t), (), put(248, 16)))
    boundary = load(245).add(Fragment.choose(lambda t: JZ(r0, t), header, complete))
    logical.add(Fragment.choose(lambda t: JZ(r0, t), boundary))
    nonstuff = load(245, r1).add([CMPI(r1, 2)])
    nonstuff.add(Fragment.choose(JFAIL, logical, [JMP(Label("delimiter"))]))
    sample.add(load(243, r1)).add([CMPI(r1, 5)])
    sample.add(Fragment.choose(JFAIL, nonstuff, stuff))
    sample.add(load(248)).add(
        [
            JZ(r0, Label("sample_ok")),
            MOV(r2, r0),
            JMP(Label("failure")),
            Label("sample_ok"),
        ]
    )
    # MOV/JMP failure is terminal; its3 clocks are not executed on success.
    normal_cycles = sample.cycles - 2
    sample.add(Fragment.delay(400 - normal_cycles - 1)).add([JMP(Label("sample"))])
    out.add(
        [Comment(f"Normal sample path: {normal_cycles} clocks before padding.")]
    ).add(sample)
    out.add(
        [
            Label("delimiter"),
            Comment(
                "r0 is CRC delimiter. Data and CRC already checked, final stuff consumed."
            ),
            CMPI(r0, 1),
            JFAIL(Label("form_error")),
            Comment(
                "Drive ACK within its bit cell; exact phase checked by independent peer."
            ),
            WAIT(81),
            SETO(0),
            WAIT(255),
            WAIT(42),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("ack_ok")),
            LDI(r2, 20),
            JMP(Label("failure")),
            Label("ack_ok"),
            WAIT(96),
            SETO(1),
            WAIT(255),
            WAIT(41),
            Comment(
                "ACK delimiter, 7 EOF bits, 3 intermission. Fixed-form recessive fields."
            ),
            LDI(r2, 11),
            Label("tail"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("form_error")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("tail")),
            Comment("Decode stored identifier into two bytes, then DLC and payload."),
            LDI(r0, 0),
            LDI(r1, 145),
            LDI(r2, 3),
            Label("id_high"),
            LOAD(r3, r1),
            SHL(r0),
            OR(r0, r3),
            ADDI(r1, 1),
            DJNZ(r2, Label("id_high")),
            LDI(r3, 0x30),
            PWRITE(r0, r3),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            LDI(r0, 0),
            LDI(r2, 8),
            Label("id_low"),
            LOAD(r3, r1),
            SHL(r0),
            OR(r0, r3),
            ADDI(r1, 1),
            DJNZ(r2, Label("id_low")),
            LDI(r3, 0x30),
            PWRITE(r0, r3),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 254),
            LDI(r1, 249),
            LOAD(r0, r1),
            MOV(r2, r0),
            PWRITE(r0, r3),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            JZ(r2, Label("output_done")),
            LDI(r1, 163),
            Label("data_byte"),
            LDI(r0, 0),
            LDI(r3, 8),
            Label("data_bit"),
            LOAD(r3, r1),
            SHL(r0),
            OR(r0, r3),
            ADDI(r1, 1),
            Comment("Byte boundary via pointer modulo8: first payload address163."),
            MOV(r3, r1),
            ADDI(r3, 253),
            ANDI(r3, 7),
            JZ(r3, Label("output_byte")),
            JMP(Label("data_bit")),
            Label("output_byte"),
            LDI(r3, 0x30),
            PWRITE(r0, r3),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            DJNZ(r2, Label("data_byte")),
            Label("output_done"),
            LDI(r1, 249),
            LOAD(r0, r1),
            ADDI(r0, 3),
            LDI(r1, 134),
            STORE(r0, r1),
            JMP(Label("publish")),
            Label("form_error"),
            LDI(r2, 17),
            Label("failure"),
            SETO(1),
            LDI(r1, 131),
            STORE(r2, r1),
            Label("publish"),
            Comment(
                "Output metadata defaults0; no per-byte nonzero metadata used here."
            ),
            LDI(r1, 128),
            LDI(r2, 16),
            LDI(r3, 0x40),
            Label("event"),
            LOAD(r0, r1),
            PWRITE(r0, r3),
            ADDI(r1, 1),
            DJNZ(r2, Label("event")),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            JMP(Label("idle")),
        ]
    )
    return out.program


if __name__ == "__main__":
    Path(__file__).with_name("can_candidate.asm").write_text(generate().to_asm())
