#!/usr/bin/env python3
"""Generate cycle-balanced generic-ISA CAN receive firmware, not an RTL engine.

The tiny assembler builder balances conditional paths with ordinary WAIT/NOP
instructions. Runtime protocol work remains visible in can_candidate.asm.
"""

from pathlib import Path


class Block:
    serial = 0

    def __init__(self, text="", cycles=None):
        self.lines = [s.strip() for s in text.splitlines() if s.strip()]
        self.cycles = (
            sum(self.cost(s) for s in self.lines) if cycles is None else cycles
        )

    @staticmethod
    def cost(line):
        op = line.split()[0]
        if line.endswith(":") or op.startswith("#"):
            return 0
        if op == "WAIT":
            return int(line.split()[1], 0) + 1
        return 2 if op in {"LOAD", "STORE", "PREAD", "PWRITE"} else 1

    def add(self, other):
        if isinstance(other, str):
            other = Block(other)
        self.lines += other.lines
        self.cycles += other.cycles
        return self

    @classmethod
    def delay(cls, cycles):
        assert cycles >= 0, cycles
        block = cls()
        while cycles:
            step = min(256, cycles)
            block.add("NOP" if step == 1 else f"WAIT {step - 1}")
            cycles -= step
        return block

    @classmethod
    def choose(cls, condition, yes, no=None):
        """condition is a taken conditional jump, lacking its target label."""
        yes = yes if isinstance(yes, cls) else cls(yes)
        no = no if isinstance(no, cls) else cls(no or "")
        cls.serial += 1
        label = f"balance_{cls.serial}"
        longest = max(yes.cycles, no.cycles + 1)
        result = cls(
            f"{condition}, {label}_yes"
            if condition.startswith("JZ")
            else f"{condition} {label}_yes"
        )
        result.add(no).add(cls.delay(longest - no.cycles - 1)).add(f"JMP {label}_end")
        result.add(f"{label}_yes:").add(yes).add(cls.delay(longest - yes.cycles))
        result.add(f"{label}_end:")
        # The linear listing contains both arms; only one executes at runtime.
        result.cycles = longest + 1
        return result


def put(address, value):
    return Block(f"LDI r1, {address}\nLDI r0, {value}\nSTORE r0, r1")


def load(address, reg="r0"):
    return Block(f"LDI r1, {address}\nLOAD {reg}, r1")


def generate():
    Block.serial = 0
    out = Block("""
    # GENERATED by build_can_rx.py. Generic instructions only; RX milestone.
    # CAN transceiver TXD=uio0 (1 recessive), RXD=uio1. 125 kbit/s at50MHz.
    # Event128..143; unstuffed bits144..241; state242..249. Valid RX envelope.
    # Header19 bits, data0..64 bits, CRC15. r2/r3 hold CRC low/high.
    SETO 1
    SETOE 1
idle:
    LDI r3, 0x22
    PREAD r0, r3
    JFAIL idle
    LDI r1, 128
    STORE r0, r1
    PREAD r0, r3
    ADDI r1, 1
    STORE r0, r1
    LDI r2, 14
record:
    PREAD r0, r3
    DJNZ r2, record
    LDI r1, 130
    LDI r0, 1
    STORE r0, r1
    ADDI r1, 1
    LDI r2, 13
    LDI r0, 0
clear_event:
    STORE r0, r1
    ADDI r1, 1
    DJNZ r2, clear_event
    LDI r3, 2
    PREAD r0, r3
    LDI r1, 132
    STORE r0, r1
    """)
    for address, value in [
        (242, 1),
        (243, 0),
        (244, 19),
        (245, 0),
        (247, 144),
        (248, 0),
    ]:
        out.add(put(address, value))
    out.add("""
    # Require 11 consecutive recessive bit times before arming SOF detection.
    LDI r2, 11
    LDI r3, 0
idle_bus:
    INBIT r0, 1
    ANDI r0, 1
    JZ r0, busy_bus
    WAIT 255
    WAIT 139
    DJNZ r2, idle_bus
    LDI r2, 0
    LDI r3, 0
sof_wait:
    INBIT r0, 1
    ANDI r0, 1
    JZ r0, sof_seen
    DJNZ r3, sof_wait
    DJNZ r2, sof_wait
    LDI r2, 6
    JMP failure
busy_bus:
    LDI r2, 11
    DJNZ r3, idle_bus
    LDI r2, 6
    JMP failure
sof_seen:
    LDI r2, 0
    LDI r3, 0
    WAIT 255
    WAIT 36
sample:
    """)
    # Each nonterminal path from sample to sample is exactly400 core clocks.
    sample = Block("INBIT r0, 1\nANDI r0, 1\nLDI r1, 246\nSTORE r0, r1")
    stuff = load(242, "r1").add("XOR r1, r0")
    stuff.add(Block.choose("JZ r1", put(248, 19)))
    stuff.add(load(246)).add("LDI r1, 242\nSTORE r0, r1").add(put(243, 1))

    logical = load(242, "r1").add("XOR r1, r0")
    same = load(243).add("ADDI r0, 1\nSTORE r0, r1")
    changed = load(246).add("LDI r1, 242\nSTORE r0, r1").add(put(243, 1))
    logical.add(Block.choose("JZ r1", same, changed))
    logical.add(load(246)).add(load(247, "r1"))
    logical.add("""
    STORE r0, r1
    ADDI r1, 1
    MOV r0, r1
    LDI r1, 247
    STORE r0, r1
    # CRC15, polynomial0x4599. Process received CRC too: valid residue is0.
    MOV r0, r3
    ANDI r0, 64
    LDI r1, 246
    LOAD r1, r1
    SHL r1
    SHL r1
    SHL r1
    SHL r1
    SHL r1
    SHL r1
    XOR r0, r1
    SHL r3
    ANDI r3, 127
    ROL r2
    MOV r1, r2
    ANDI r1, 1
    OR r3, r1
    ANDI r2, 254
    """)
    logical.add(Block.choose("JZ r0", "", "XORI r2, 0x99\nXORI r3, 0x45"))
    logical.add(load(244)).add("ADDI r0, 255\nSTORE r0, r1")
    header = Block("""
    # Only standard data frames: RTR/IDE/r0 must all be0 in this milestone.
    LDI r1, 156
    LOAD r0, r1
    ADDI r1, 1
    LOAD r1, r1
    OR r0, r1
    LDI r1, 158
    LOAD r1, r1
    OR r0, r1
    """)
    header.add(Block.choose("JZ r0", "", put(248, 18)))
    header.add("LDI r0, 0")
    for address in range(159, 163):
        header.add(f"LDI r1, {address}\nLOAD r1, r1\nSHL r0\nOR r0, r1")
    header.add("LDI r1, 249\nSTORE r0, r1\nCMPLTI r0, 9")
    header.add(Block.choose("JFAIL", put(248, 18)))
    header.add(load(249)).add(
        "SHL r0\nSHL r0\nSHL r0\nADDI r0, 15\nLDI r1, 244\nSTORE r0, r1"
    )
    header.add(put(245, 1))
    complete = put(245, 2).add("MOV r0, r2\nOR r0, r3")
    complete.add(Block.choose("JZ r0", "", put(248, 16)))
    boundary = load(245).add(Block.choose("JZ r0", header, complete))
    logical.add(Block.choose("JZ r0", boundary))
    nonstuff = load(245, "r1").add("CMPI r1, 2")
    nonstuff.add(Block.choose("JFAIL", logical, "JMP delimiter"))
    sample.add(load(243, "r1")).add("CMPI r1, 5")
    sample.add(Block.choose("JFAIL", nonstuff, stuff))
    sample.add(load(248)).add("JZ r0, sample_ok\nMOV r2, r0\nJMP failure\nsample_ok:")
    # MOV/JMP failure is terminal; its3 clocks are not executed on success.
    normal_cycles = sample.cycles - 2
    sample.add(Block.delay(400 - normal_cycles - 1)).add("JMP sample")
    out.add(f"# Normal sample path: {normal_cycles} clocks before padding.").add(sample)
    out.add("""
delimiter:
    # r0 is CRC delimiter. Data and CRC already checked, final stuff consumed.
    CMPI r0, 1
    JFAIL form_error
    # Drive ACK within its bit cell; exact phase checked by independent peer.
    WAIT 81
    SETO 0
    WAIT 255
    WAIT 42
    INBIT r0, 1
    ANDI r0, 1
    JZ r0, ack_ok
    LDI r2, 20
    JMP failure
ack_ok:
    WAIT 96
    SETO 1
    WAIT 255
    WAIT 41
    # ACK delimiter, 7 EOF bits, 3 intermission. Fixed-form recessive fields.
    LDI r2, 11
tail:
    INBIT r0, 1
    ANDI r0, 1
    JZ r0, form_error
    WAIT 255
    WAIT 139
    DJNZ r2, tail
    # Decode stored identifier into two bytes, then DLC and payload.
    LDI r0, 0
    LDI r1, 145
    LDI r2, 3
id_high:
    LOAD r3, r1
    SHL r0
    OR r0, r3
    ADDI r1, 1
    DJNZ r2, id_high
    LDI r3, 0x30
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    LDI r0, 0
    LDI r2, 8
id_low:
    LOAD r3, r1
    SHL r0
    OR r0, r3
    ADDI r1, 1
    DJNZ r2, id_low
    LDI r3, 0x30
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 254
    LDI r1, 249
    LOAD r0, r1
    MOV r2, r0
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    JZ r2, output_done
    LDI r1, 163
data_byte:
    LDI r0, 0
    LDI r3, 8
data_bit:
    LOAD r3, r1
    SHL r0
    OR r0, r3
    ADDI r1, 1
    # Byte boundary via pointer modulo8: first payload address163.
    MOV r3, r1
    ADDI r3, 253
    ANDI r3, 7
    JZ r3, output_byte
    JMP data_bit
output_byte:
    LDI r3, 0x30
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    DJNZ r2, data_byte
output_done:
    LDI r1, 249
    LOAD r0, r1
    ADDI r0, 3
    LDI r1, 134
    STORE r0, r1
    JMP publish
form_error:
    LDI r2, 17
failure:
    SETO 1
    LDI r1, 131
    STORE r2, r1
publish:
    # Output metadata defaults0; no per-byte nonzero metadata used here.
    LDI r1, 128
    LDI r2, 16
    LDI r3, 0x40
event:
    LOAD r0, r1
    PWRITE r0, r3
    ADDI r1, 1
    DJNZ r2, event
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    JMP idle
    """)
    return "\n".join(out.lines) + "\n"


if __name__ == "__main__":
    Path(__file__).with_name("can_candidate.asm").write_text(generate())
