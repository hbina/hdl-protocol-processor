#!/usr/bin/env python3
"""RX CRC/stuff/form error signaling sharing generic firmware flag machinery."""

from pathlib import Path

from build_can_fault_equal import generate as fault_source
from build_can_rx import Block


def generate():
    source = fault_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    # Defer CRC status16 while consuming the possible final stuff bit. Other
    # bit-stream faults still take the immediate next-bit signaling path.
    ignore_crc = Block("CMPI r0, 16").add(Block.choose("JFAIL", "", "LDI r0, 0"))
    replace(
        "LDI r1, 248\nLOAD r0, r1\nJZ r0, rx_sample_ok\nMOV r2, r0\nJMP failure",
        "LDI r1, 248\nLOAD r0, r1\n"
        + "\n".join(ignore_crc.lines)
        + """
JZ r0, rx_sample_ok
MOV r2, r0
JMP rx_error_dispatch""",
    )
    # The normal RX path gains4 clocks, preserving the sample window's end.
    replace("LDI r7, 27\nrx_edge_poll:", "LDI r7, 26\nrx_edge_poll:")
    replace("rx_no_edge_window:\nWAIT 251", "rx_no_edge_window:\nWAIT 247")

    replace(
        """rx_delimiter:
# r0 is CRC rx_delimiter. Data and CRC already checked, final stuff consumed.
CMPI r0, 1
JFAIL rx_form_error
#50% sample: ACK starts200 clocks after CRC-delimiter sample.
WAIT 181""",
        """rx_delimiter:
CMPI r0, 1
JFAIL rx_delimiter_form_error
LDI r1, 248
LOAD r0, r1
JZ r0, rx_valid_crc
LDI r2, 16
WAIT 255
WAIT 255
WAIT 255
WAIT 8
# ACK delimiter sample,800 clocks after CRC delimiter. Do not ACK bad CRC.
INBIT r0, 1
ANDI r0, 1
WAIT 147
JMP rx_fault_prepare
rx_valid_crc:
WAIT 177""",
    )
    replace("LDI r2, 20\nJMP failure", "LDI r2, 20\nWAIT 145\nJMP rx_fault_prepare")
    replace(
        "rx_form_error:\nLDI r2, 17\nJMP failure",
        """rx_form_error:
# r2=11 at ACK delimiter,10..4 at EOF,3..1 at intermission.
# Preserve the older local-only limitation for last EOF/intermission traffic.
CMPLTI r2, 5
JFAIL rx_tail_form_error
LDI r2, 17
JMP failure
rx_tail_form_error:
LDI r2, 17
WAIT 143
JMP rx_fault_prepare
rx_delimiter_form_error:
LDI r2, 17
WAIT 130
JMP rx_fault_prepare""",
    )

    # TX reaches the flag drive at its next boundary exactly as before. RX
    # enters after151 clocks of its50% sample and uses its own remaining wait.
    replace(
        """JZ r7, active_flag_start
WAIT 64
SETO 1
JMP flag_started
active_flag_start:
WAIT 64
SETO 0
JMP flag_started""",
        """WAIT 63
JMP flag_drive
flag_drive:
JZ r7, active_flag_start
SETO 1
JMP flag_started
active_flag_start:
SETO 0
NOP""",
    )
    extra = Block("""rx_error_dispatch:
CMPI r2, 18
JFAIL rx_fault_prepare
JMP failure
rx_fault_prepare:
LDI r6, 6
LDI r1, 131
STORE r2, r1
CALL passive_state
MOV r7, r0
LDI r4, 0
WAIT 29
JMP flag_drive""")
    # Make the existing REC increment a reusable non-nesting generic leaf.
    begin = source.index("increment_rec:\n")
    end = source.index("publish:\n", begin)
    old_rec = source[begin:end]
    assert "STORE r0, r1" in old_rec
    source = (
        source[:begin]
        + "increment_rec:\nCALL increment_rec_leaf\nJMP publish\n"
        + source[end:]
    )
    rec = Block("LDI r1, 250\nLOAD r0, r1\nCMPI r0, 255")
    rec.add(Block.choose("JFAIL", "ADDI r0, 1\nSTORE r0, r1"))
    extra.add("increment_rec_leaf:").add(rec).add("RET")
    # The TX counter body is cycle-balanced at34 clocks. Select REC instead
    # for receive-error mode, retaining the first-delimiter sample's phase.
    begin = source.index("CMPI r2, 21\n", source.index("flag_finished:"))
    end = source.index("LDI r2, 8\nLDI r3, 32", begin)
    tx_counter = Block(source[begin:end], cycles=34)
    counter = Block("CMPI r6, 6").add(
        Block.choose(
            "JFAIL",
            tx_counter,
            Block("CALL increment_rec_leaf", cycles=1 + rec.cycles + 1),
        )
    )
    assert counter.cycles == 36
    source = source[:begin] + "\n".join(counter.lines) + "\n" + source[end:]
    replace(
        "LDI r2, 8\nLDI r3, 32\nWAIT 255\nWAIT 3\nJMP error_delimiter_sample",
        "LDI r2, 8\nLDI r3, 32\nWAIT 255\nWAIT 1\nJMP error_delimiter_sample",
    )
    replace(
        "WAIT 96\nLDI r1, 255\nLOAD r0, r1\nJZ r0, not_bus_off",
        "WAIT 96\nCMPI r6, 6\nJFAIL error_was_transmit\nJMP publish\nerror_was_transmit:\nLDI r1, 255\nLOAD r0, r1\nJZ r0, not_bus_off",
    )
    return (source + "\n".join(extra.lines) + "\n").replace(
        "# GENERATED by build_can_fault_equal.py.",
        "# GENERATED by build_can_rx_flags.py. RX error flags; capacity-only until assembled.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_rx_flags_candidate.asm").write_text(generate())
