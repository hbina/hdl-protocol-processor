#!/usr/bin/env python3
"""Draft bounded CAN EOF/intermission/overload service in generic firmware.

Keep the earlier1,024-word image frozen. A new integration may exceed its
model's actual instruction limit; that failure is measured before simulation.
"""

from pathlib import Path

from build_can_flag_compact import generate as prior_source
from tools.program import Program
from tools.isa import (
    ANDI,
    CMPI,
    DJNZ,
    INBIT,
    JFAIL,
    JMP,
    JZ,
    LDI,
    Label,
    NOP,
    SETO,
    WAIT,
    r0,
    r2,
    r3,
    r7,
)
from tools.program import Comment


def generate():
    source = prior_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    replace(
        [
            LDI(r2, 11),
            Label("rx_tail"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("rx_form_error")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("rx_tail")),
            Comment("Decode stored identifier into two bytes, then DLC and payload."),
        ],
        [
            LDI(r2, 7),
            Label("rx_tail"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("rx_form_error")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("rx_tail")),
            Comment("The receiver does not classify dominant EOF7 as a form error."),
            Comment(
                "The capture ABI returns one frame; third-intermission SOF is accepted as"
            ),
            Comment(
                "a next-frame boundary, but continuous reception remains unsupported."
            ),
            LDI(r2, 3),
            LDI(r7, 3),
            INBIT(r0, 1),
            WAIT(255),
            WAIT(140),
            Label("rx_intermission"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("rx_intermission_dominant")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("rx_intermission")),
            Label("rx_decode"),
            Comment("Decode stored identifier into two bytes, then DLC and payload."),
        ],
    )
    begin = source.index([Label("rx_form_error")])
    end = source.index([Label("rx_delimiter_form_error")], begin)
    source = Program(
        source[:begin]
        + [
            Label("rx_form_error"),
            LDI(r2, 17),
            WAIT(145),
            JMP(Label("rx_fault_prepare")),
        ]
        + source[end:]
    )
    source += [
        Label("rx_intermission_dominant"),
        CMPI(r2, 1),
        JFAIL(Label("rx_overload")),
        JMP(Label("rx_decode")),
        Label("rx_overload"),
        NOP(),
        Label("rx_overload_prepare"),
        Comment("At most two generated overload flags per captured frame. A further"),
        Comment(
            "disturbed boundary is a local bounded-service timeout, not compliance."
        ),
        DJNZ(r7, Label("rx_overload_allowed")),
        JMP(Label("recovery_timeout")),
        Label("rx_overload_allowed"),
        LDI(r3, 6),
        WAIT(191),
        SETO(0),
        Label("rx_overload_bit"),
        WAIT(255),
        WAIT(141),
        DJNZ(r3, Label("rx_overload_bit")),
        WAIT(4),
        SETO(1),
        LDI(r2, 8),
        LDI(r3, 32),
        WAIT(196),
        Label("rx_overload_delimiter"),
        INBIT(r0, 1),
        ANDI(r0, 1),
        JZ(r0, Label("rx_overload_dominant")),
        DJNZ(r2, Label("rx_overload_recessive")),
        LDI(r2, 3),
        WAIT(255),
        WAIT(137),
        JMP(Label("rx_intermission")),
        Label("rx_overload_dominant"),
        CMPI(r2, 1),
        JFAIL(Label("rx_overload_extend")),
        JMP(Label("rx_overload_prepare")),
        Label("rx_overload_recessive"),
        NOP(),
        JMP(Label("rx_overload_more")),
        Label("rx_overload_extend"),
        LDI(r2, 8),
        Label("rx_overload_more"),
        DJNZ(r3, Label("rx_overload_delay")),
        JMP(Label("recovery_timeout")),
        Label("rx_overload_delay"),
        WAIT(255),
        WAIT(135),
        JMP(Label("rx_overload_delimiter")),
    ]
    return source.replace_comment_text(
        "GENERATED by build_can_flag_compact.py.",
        "GENERATED by build_can_tail.py. UNVERIFIED capacity integration; bounded RX tail service.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_tail_candidate.asm").write_text(generate().to_asm())
