#!/usr/bin/env python3
"""Draft bounded CAN EOF/intermission/overload service in generic firmware.

Keep the earlier1,024-word image frozen. A new integration may exceed its
model's actual instruction limit; that failure is measured before simulation.
"""

from pathlib import Path

from build_can_flag_compact import generate as prior_source


def generate():
    source = prior_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    replace(
        """LDI r2, 11
rx_tail:
INBIT r0, 1
ANDI r0, 1
JZ r0, rx_form_error
WAIT 255
WAIT 139
DJNZ r2, rx_tail
# Decode stored identifier""",
        """LDI r2, 7
rx_tail:
INBIT r0, 1
ANDI r0, 1
JZ r0, rx_form_error
WAIT 255
WAIT 139
DJNZ r2, rx_tail
# The receiver does not classify dominant EOF7 as a form error.
# The capture ABI returns one frame; third-intermission SOF is accepted as
# a next-frame boundary, but continuous reception remains unsupported.
LDI r2, 3
LDI r7, 3
INBIT r0, 1
WAIT 255
WAIT 140
rx_intermission:
INBIT r0, 1
ANDI r0, 1
JZ r0, rx_intermission_dominant
WAIT 255
WAIT 139
DJNZ r2, rx_intermission
rx_decode:
# Decode stored identifier""",
    )
    begin = source.index("rx_form_error:\n")
    end = source.index("rx_delimiter_form_error:\n", begin)
    source = (
        source[:begin]
        + """rx_form_error:
LDI r2, 17
WAIT 145
JMP rx_fault_prepare
"""
        + source[end:]
    )
    source += """
rx_intermission_dominant:
CMPI r2, 1
JFAIL rx_overload
JMP rx_decode
rx_overload:
NOP
rx_overload_prepare:
# At most two generated overload flags per captured frame. A further
# disturbed boundary is a local bounded-service timeout, not compliance.
DJNZ r7, rx_overload_allowed
JMP recovery_timeout
rx_overload_allowed:
LDI r3, 6
WAIT 191
SETO 0
rx_overload_bit:
WAIT 255
WAIT 141
DJNZ r3, rx_overload_bit
WAIT 4
SETO 1
LDI r2, 8
LDI r3, 32
WAIT 196
rx_overload_delimiter:
INBIT r0, 1
ANDI r0, 1
JZ r0, rx_overload_dominant
DJNZ r2, rx_overload_recessive
LDI r2, 3
WAIT 255
WAIT 137
JMP rx_intermission
rx_overload_dominant:
CMPI r2, 1
JFAIL rx_overload_extend
JMP rx_overload_prepare
rx_overload_recessive:
NOP
JMP rx_overload_more
rx_overload_extend:
LDI r2, 8
rx_overload_more:
DJNZ r3, rx_overload_delay
JMP recovery_timeout
rx_overload_delay:
WAIT 255
WAIT 135
JMP rx_overload_delimiter
"""
    return source.replace(
        "# GENERATED by build_can_flag_compact.py.",
        "# GENERATED by build_can_tail.py. UNVERIFIED capacity integration; bounded RX tail service.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_tail_candidate.asm").write_text(generate())
