#!/usr/bin/env python3
"""Generate a standalone generic-ISA Classical CAN transmit experiment.

CRC, stuffing, monitoring and arbitration decisions are instructions. The
builder only calculates padding and emits assembly; no protocol RTL is added.
"""

from pathlib import Path

from fragments import Fragment, load, put
from tools.isa import (
    ADDI,
    ANDI,
    CMPI,
    CMPLTI,
    DJNZ,
    INBIT,
    JFAIL,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    MOV,
    OR,
    OUTBIT,
    PREAD,
    PWRITE,
    ROL,
    SETO,
    SETOE,
    SHL,
    STORE,
    WAIT,
    XOR,
    XORI,
    r0,
    r1,
    r2,
    r3,
)
from tools.program import Comment


def unpack(label):
    return Fragment(
        [
            Label(str(label)),
            ROL(r0),
            MOV(r3, r0),
            ANDI(r3, 1),
            STORE(r3, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label(label)),
        ]
    )


def generate():
    Fragment.serial = 100
    out = Fragment(
        [
            Comment(
                "GENERATED by build_can_tx.py. TX-only capacity/timing experiment."
            ),
            Comment("TXD=uio0, RXD=uio1. 50MHz core, 125kbit/s. No protocol RTL."),
            Comment(
                "Arguments[0:3]=identifier high3 bits, identifier low8 bits, DLC0..8."
            ),
            Comment(
                "Input FIFO supplies DLC arbitrary payload bytes. No returned data."
            ),
            Comment(
                "Event128..143, logical bits144..241, state242..254. Valid envelopes."
            ),
            SETO(1),
            SETOE(1),
            Label("idle"),
            LDI(r3, 0x22),
            PREAD(r0, r3),
            JFAIL(Label("idle")),
            LDI(r1, 128),
            STORE(r0, r1),
            PREAD(r0, r3),
            ADDI(r1, 1),
            STORE(r0, r1),
            LDI(r2, 14),
            Label("record"),
            PREAD(r0, r3),
            DJNZ(r2, Label("record")),
            LDI(r1, 130),
            LDI(r0, 1),
            STORE(r0, r1),
            ADDI(r1, 1),
            LDI(r2, 13),
            LDI(r0, 0),
            Label("clear_event"),
            STORE(r0, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label("clear_event")),
            LDI(r3, 2),
            PREAD(r0, r3),
            LDI(r1, 132),
            STORE(r0, r1),
            Comment(
                "Build unstuffed SOF, identifier, control and data in private RAM."
            ),
            LDI(r1, 144),
            LDI(r0, 0),
            STORE(r0, r1),
            ADDI(r1, 1),
            LDI(r3, 0),
            LOAD(r0, r3),
            SHL(r0),
            SHL(r0),
            SHL(r0),
            SHL(r0),
            SHL(r0),
            LDI(r2, 3),
        ]
    )
    out.add(unpack("id_high"))
    out.add([LDI(r3, 1), LOAD(r0, r3), LDI(r2, 8)])
    out.add(unpack("id_low"))
    out.add(
        [
            LDI(r0, 0),
            LDI(r2, 3),
            Label("flags"),
            STORE(r0, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label("flags")),
        ]
    )
    out.add(
        [
            LDI(r3, 2),
            LOAD(r0, r3),
            LDI(r3, 252),
            STORE(r0, r3),
            SHL(r0),
            SHL(r0),
            SHL(r0),
            SHL(r0),
            LDI(r2, 4),
        ]
    )
    out.add(unpack("dlc_bits"))
    out.add(
        [
            LDI(r3, 252),
            LOAD(r0, r3),
            JZ(r0, Label("crc_begin")),
            Label("payload_byte"),
            LDI(r3, 0x11),
            PREAD(r0, r3),
            LDI(r2, 8),
        ]
    )
    out.add(unpack("payload_bits"))
    out.add(
        [
            LDI(r3, 252),
            LOAD(r0, r3),
            ADDI(r0, 255),
            STORE(r0, r3),
            JZ(r0, Label("crc_begin")),
            JMP(Label("payload_byte")),
            Label("crc_begin"),
            MOV(r0, r1),
            LDI(r1, 253),
            STORE(r0, r1),
            LDI(r1, 2),
            LOAD(r0, r1),
            LDI(r1, 132),
            STORE(r0, r1),
            LDI(r2, 0),
            LDI(r3, 0),
        ]
    )
    out.add(put(247, 144))
    out.add(
        [
            Label("crc_bit"),
            LDI(r1, 247),
            LOAD(r1, r1),
            LOAD(r0, r1),
            LDI(r1, 246),
            STORE(r0, r1),
            MOV(r0, r3),
            ANDI(r0, 64),
            LOAD(r1, r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            SHL(r1),
            XOR(r0, r1),
            SHL(r3),
            ANDI(r3, 127),
            ROL(r2),
            MOV(r1, r2),
            ANDI(r1, 1),
            OR(r3, r1),
            ANDI(r2, 254),
        ]
    )
    out.add(Fragment.choose(lambda t: JZ(r0, t), (), [XORI(r2, 0x99), XORI(r3, 0x45)]))
    out.add(
        [
            LDI(r1, 247),
            LOAD(r0, r1),
            ADDI(r0, 1),
            STORE(r0, r1),
            LDI(r1, 253),
            LOAD(r1, r1),
            XOR(r0, r1),
            JZ(r0, Label("crc_append")),
            JMP(Label("crc_bit")),
            Label("crc_append"),
            MOV(r0, r2),
            LDI(r2, 254),
            STORE(r0, r2),
            MOV(r0, r3),
            SHL(r0),
            LDI(r2, 7),
        ]
    )
    out.add(unpack("crc_high"))
    out.add([LDI(r3, 254), LOAD(r0, r3), LDI(r2, 8)])
    out.add(unpack("crc_low"))
    out.add([MOV(r0, r1), LDI(r1, 253), STORE(r0, r1)])
    for address, value in [(242, 1), (243, 0), (245, 0), (247, 144)]:
        out.add(put(address, value))
    out.add(
        [
            Comment(
                "Controlled-bus idle qualification. Still no full CAN idle/error state."
            ),
            LDI(r2, 11),
            LDI(r3, 0),
            Label("idle_bus"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("busy_bus")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("idle_bus")),
            JMP(Label("tx_cell")),
            Label("busy_bus"),
            LDI(r2, 11),
            DJNZ(r3, Label("idle_bus")),
            LDI(r2, 6),
            JMP(Label("failure")),
            Label("tx_cell"),
        ]
    )
    # Fetch each normal or inserted bit in equal time. A final pending stuff
    # bit is sent before transitioning to the unstuffed CRC delimiter.
    stuff = load(242).add([XORI(r0, 1), STORE(r0, r1)]).add(put(243, 1))
    stuff.add(load(242)).add([LDI(r1, 246), STORE(r0, r1)])
    stuff.add(put(244, 1))
    logical = load(247, r1).add(
        [LOAD(r0, r1), ADDI(r1, 1), MOV(r2, r1), LDI(r1, 247), STORE(r2, r1)]
    )
    logical.add([LDI(r1, 246), STORE(r0, r1)])
    logical.add(load(242, r1)).add([XOR(r1, r0)])
    same = load(243).add([ADDI(r0, 1), STORE(r0, r1)])
    changed = load(246).add([LDI(r1, 242), STORE(r0, r1)]).add(put(243, 1))
    logical.add(Fragment.choose(lambda t: JZ(r1, t), same, changed))
    logical.add(put(244, 0))
    end = put(245, 1).add(put(246, 1))
    next_bit = load(247).add(load(253, r1)).add([XOR(r0, r1)])
    next_bit.add(Fragment.choose(lambda t: JZ(r0, t), end, logical))
    fetch = load(243).add([CMPI(r0, 5)])
    fetch.add(Fragment.choose(JFAIL, next_bit, stuff)).add(load(246))
    fetch_cycles = fetch.cycles
    out.add([Comment(f"Balanced fetch path: {fetch_cycles} clocks.")]).add(fetch)
    out.add(
        [
            Label("tx_drive"),
            OUTBIT(r0, 0),
            LDI(r1, 245),
            LOAD(r1, r1),
            JZ(r1, Label("normal_cell")),
            JMP(Label("tx_tail")),
            Label("normal_cell"),
        ]
    )
    # OUTBIT1 + LDI1 + LOAD2 + JZ1 =5 cycles before this delay.
    out.add(Fragment.delay(300 - 5))
    out.add(
        [
            Label("tx_sample"),
            INBIT(r1, 1),
            ANDI(r1, 1),
            XOR(r1, r0),
            JZ(r1, Label("sample_ok")),
            JMP(Label("mismatch")),
            Label("sample_ok"),
        ]
    )
    out.add(Fragment.delay(400 - 300 - 4 - 1 - fetch_cycles)).add(
        [JMP(Label("tx_cell"))]
    )
    out.add(
        [
            Label("mismatch"),
            Comment(
                "Release immediately on loss. No automatic retry or winner RX yet."
            ),
            SETO(1),
            JZ(r0, Label("bit_error")),
            LDI(r1, 244),
            LOAD(r0, r1),
            JZ(r0, Label("arbitration_check")),
            JMP(Label("bit_error")),
            Label("arbitration_check"),
            LDI(r1, 247),
            LOAD(r0, r1),
            CMPLTI(r0, 157),
            JFAIL(Label("bit_error")),
            LDI(r2, 22),
            JMP(Label("failure")),
            Label("bit_error"),
            LDI(r2, 21),
            JMP(Label("failure")),
            Label("tx_tail"),
            Comment(
                "Enter6 clocks after CRC-delimiter OUTBIT. Sample at75% of each cell."
            ),
            WAIT(255),
            WAIT(37),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("form_error")),
            WAIT(255),
            WAIT(140),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("acknowledged")),
            LDI(r2, 24),
            JMP(Label("failure")),
            Label("acknowledged"),
            WAIT(255),
            WAIT(139),
            LDI(r2, 11),
            Label("tail"),
            INBIT(r0, 1),
            ANDI(r0, 1),
            JZ(r0, Label("form_error")),
            WAIT(255),
            WAIT(139),
            DJNZ(r2, Label("tail")),
            JMP(Label("publish")),
            Label("form_error"),
            LDI(r2, 17),
            Label("failure"),
            SETO(1),
            LDI(r1, 131),
            STORE(r2, r1),
            Label("publish"),
            LDI(r1, 128),
            LDI(r2, 16),
            LDI(r3, 0x40),
            Label("event"),
            LOAD(r0, r1),
            PWRITE(r0, r3),
            ADDI(r1, 1),
            DJNZ(r2, Label("event")),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            JMP(Label("idle")),
        ]
    )
    return out.program


if __name__ == "__main__":
    Path(__file__).with_name("can_tx_candidate.asm").write_text(generate().to_asm())
