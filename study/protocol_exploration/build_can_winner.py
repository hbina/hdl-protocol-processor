#!/usr/bin/env python3
"""CAN winner reception/retransmission using the existing generic ISA only."""

from pathlib import Path

from build_can_recovery import generate as recovery_source
from build_can_rx import Block, load, put


def generate():
    source = recovery_source()

    def replace(old, new):
        nonlocal source
        assert source.count(old) == 1, old
        source = source.replace(old, new)

    replace(
        "legacy_dispatch:\nCMPI r0, 2",
        """legacy_dispatch:
CMPI r0, 4
JFAIL ordinary_dispatch
LDI r6, 2
JMP tx_entry
ordinary_dispatch:
CMPI r0, 2""",
    )
    replace("tx_entry:\n", "tx_entry:\nLDI r7, 136\n")
    replace(
        "tx_payload_byte:\nLDI r3, 0x11\nPREAD r0, r3",
        """tx_payload_byte:
CMPI r6, 4
JFAIL payload_from_fifo
LOAD r0, r7
JMP payload_ready
payload_from_fifo:
LDI r3, 0x11
PREAD r0, r3
STORE r0, r7
payload_ready:
ADDI r7, 1""",
    )
    replace(
        "ADDI r5, 1\nLDI r1, 242",
        """ADDI r5, 1
CMPI r6, 4
JFAIL tx_mode_ready
LDI r6, 2
tx_mode_ready:
LDI r4, 0
LDI r7, 0
LDI r1, 242""",
    )
    # Preserve the previous dominant run before the balanced fetch updates it.
    cache = load(242)
    cache.add(Block.choose("JZ r0", load(243), "LDI r0, 0"))
    cache.add("LDI r1, 248\nSTORE r0, r1")
    replace("tx_tx_cell:\n", "tx_tx_cell:\n" + "\n".join(cache.lines) + "\n")
    replace(
        "tx_sample_ok:\nWAIT 44",
        "tx_sample_ok:\n" + "\n".join(Block.delay(45 - cache.cycles).lines),
    )

    # Mirror the logical TX prefix CRC in generic registers. Stuff bits do not
    # enter CRC. If arbitration flips the current1 to0, XOR polynomial0x4599
    # repairs precisely that step; earlier logical bits were common to both.
    crc = Block("""MOV r1, r7
ANDI r1, 64
MOV r2, r0
SHL r2
SHL r2
SHL r2
SHL r2
SHL r2
SHL r2
XOR r1, r2
SHL r7
ANDI r7, 127
ROL r4
MOV r2, r4
ANDI r2, 1
OR r7, r2
ANDI r4, 254""")
    crc.add(Block.choose("JZ r1", "", "XORI r4, 0x99\nXORI r7, 0x45"))
    mirror = load(244, "r1").add(Block.choose("JZ r1", crc))
    replace(
        "tx_normal_cell:\nWAIT 255\nWAIT 38",
        "tx_normal_cell:\n"
        + "\n".join(mirror.lines + Block.delay(295 - mirror.cycles).lines),
    )
    replace(
        "LDI r2, 22\nJMP failure",
        """CMPI r6, 2
JFAIL legacy_arbitration_loss
JMP winner_loss
legacy_arbitration_loss:
LDI r2, 22
JMP failure""",
    )
    # At winner_loss entry,19 clocks have elapsed since the TX sample.
    loss = Block("""winner_loss:
LDI r6, 3
XORI r4, 0x99
XORI r7, 0x45
LDI r1, 247
LOAD r1, r1
MOV r0, r1
ADDI r1, 255
LDI r2, 0
STORE r2, r1
# Remaining header bits =163-next logical pointer, modulo256.
XORI r0, 255
ADDI r0, 164
LDI r1, 244
STORE r0, r1""")
    loss.add(put(242, 0))
    loss.add(load(248)).add("ADDI r0, 1\nLDI r1, 243\nSTORE r0, r1")
    loss.add(put(245, 0)).add(put(248, 0))
    loss.add("MOV r2, r4\nMOV r3, r7")
    loss.add(Block.delay(400 - 19 - loss.cycles - 1)).add("JMP rx_sample")
    source += "\n".join(loss.lines) + "\n"

    replace(
        """rx_output_done:
LDI r1, 249
LOAD r0, r1
ADDI r0, 3
LDI r1, 134
STORE r0, r1
JMP publish""",
        """rx_output_done:
LDI r1, 249
LOAD r0, r1
ADDI r0, 3
MOV r2, r0
LDI r1, 134
LOAD r0, r1
accumulate_output:
ADDI r0, 1
DJNZ r2, accumulate_output
STORE r0, r1
CMPI r6, 3
JFAIL publish
CMPLTI r5, 3
JFAIL winner_attempts_exhausted
LDI r6, 4
JMP tx_entry
winner_attempts_exhausted:
LDI r2, 22
JMP failure""",
    )
    replace(
        """publish:
JZ r6, ordinary_event
LDI r1, 136
STORE r5, r1
ordinary_event:""",
        """publish:
LDI r1, 136
LDI r0, 0
JZ r6, detail_ready
MOV r0, r5
detail_ready:
STORE r0, r1
LDI r1, 137
LDI r2, 7
LDI r0, 0
clear_saved_payload:
STORE r0, r1
ADDI r1, 1
DJNZ r2, clear_saved_payload""",
    )
    # r4 is now CRC low. Use the already-existing attempt counter for the cap.
    replace(
        "ack_error:\nJZ r6, legacy_no_ack\nADDI r4, 255",
        "ack_error:\nJZ r6, legacy_no_ack\nNOP",
    )
    replace("JZ r4, retry_exhausted", "CMPLTI r5, 3\nJFAIL retry_exhausted")
    replace(
        "ADDI r5, 1\nWAIT 27\nJMP tx_tx_cell",
        "LDI r4, 0\nLDI r7, 0\nADDI r5, 1\n"
        + "\n".join(Block.delay(28 - 1 - 2 - cache.cycles).lines)
        + "\nJMP tx_tx_cell",
    )
    replace("retry_exhausted:\nWAIT 95", "retry_exhausted:\nWAIT 94")
    return source.replace(
        "# GENERATED by build_can_recovery.py.",
        "# GENERATED by build_can_winner.py. Operation4=TX/winner RX/retry.",
    )


if __name__ == "__main__":
    Path(__file__).with_name("can_winner_candidate.asm").write_text(generate())
