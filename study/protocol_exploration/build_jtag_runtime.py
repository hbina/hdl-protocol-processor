#!/usr/bin/env python3
"""Validated JTAG scan requests, entirely in the unchanged generic ISA."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load(address, reg="r0"):
    return f"LDI r1, {address}\nLOAD {reg}, r1\n"


def generate():
    probe = (ROOT / "firmware/jtag_probe.asm").read_text()
    boot = (
        "\n".join(
            line
            for line in probe.split("idle:\n", 1)[0].splitlines()
            if not line.lstrip().startswith("#")
        )
        + "\n"
    )
    runtime = (ROOT / "firmware/runtime.asm").read_text()
    header = runtime.split("idle:\n", 1)[1].split("    # Input must match", 1)[0]
    # Keep the existing generic request/event/record validation implementation;
    # protocol-specific argument semantics below remain ordinary instructions.
    source = "# GENERATED by build_jtag_runtime.py; four-register capacity model.\n"
    source += boot + "idle:\n" + header.replace("DJNZ r2, next", "DJNZ r2, record_next")
    source += load(130) + "LDI r2, 2\nCMPI r0, 1\nJFAIL reject\n"
    source += (
        load(132)
        + load(134, "r3")
        + """LDI r2, 3
JZ r0, argument_length
JMP reject
argument_length:
CMPI r3, 2
JFAIL reject
"""
    )
    source += load(0) + "CMPLTI r0, 2\nJFAIL reject\n"
    source += load(1) + "JZ r0, reject\nCMPLTI r0, 9\nJFAIL reject\n"
    source += (
        load(136)
        + load(148, "r3")
        + """XOR r0, r3
LDI r2, 4
JZ r0, input_matches
JMP reject
input_matches:
JZ r3, reject
"""
    )
    source += (
        load(138)
        + """CMPLTI r0, 65
JFAIL reject
CMPLT r0, r3
JFAIL valid
JMP reject
valid:
"""
    )
    source += (
        load(148)
        + """LDI r1, 150
STORE r0, r1
LDI r1, 160
STORE r0, r1
"""
    )
    body = probe.split("    # Run-Test/Idle", 1)[1].split("publish:\n", 1)[0]
    source += "# Run-Test/Idle" + body + "publish:\n" + probe.split("publish:\n", 1)[1]
    source += """reject:
LDI r1, 147
STORE r2, r1
LDI r3, 0x11
discard:
PREAD r0, r3
JFAIL publish
JMP discard
record_next:
PREAD r0, r3
JMP request
"""
    return (
        "\n".join(line.strip() for line in source.splitlines() if line.strip()) + "\n"
    )


if __name__ == "__main__":
    Path(__file__).with_name("jtag_runtime_candidate.asm").write_text(generate())
