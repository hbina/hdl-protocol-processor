#!/usr/bin/env python3
"""Validated JTAG scan requests, entirely in the unchanged generic ISA."""

from pathlib import Path

import isa_variants  # noqa: F401  (puts the repository root on sys.path)

from tools.program import Program
from tools.assembler import parse
from tools.isa import (
    CMPI,
    CMPLT,
    CMPLTI,
    DJNZ,
    JFAIL,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    PREAD,
    STORE,
    XOR,
    r0,
    r1,
    r2,
    r3,
)
from tools.program import Comment

ROOT = Path(__file__).resolve().parents[2]


def load(address, reg=r0):
    return [LDI(r1, address), LOAD(reg, r1)]


def generate():
    probe = parse((ROOT / "firmware/jtag_probe.asm").read_text())
    boot = probe.split([Label("idle")], 1)[0].without_comments()
    runtime = parse((ROOT / "firmware/runtime.asm").read_text())
    header = runtime.split([Label("idle")], 1)[1]
    header = header[: header.comment_index("Input must match")]
    # Keep the existing generic request/event/record validation implementation;
    # protocol-specific argument semantics below remain ordinary instructions.
    source = Program(
        [Comment("GENERATED by build_jtag_runtime.py; four-register capacity model.")]
    )
    source += (
        boot
        + [Label("idle")]
        + header.replace([DJNZ(r2, Label("next"))], [DJNZ(r2, Label("record_next"))])
    )
    source += load(130) + [LDI(r2, 2), CMPI(r0, 1), JFAIL(Label("reject"))]
    source += (
        load(132)
        + load(134, r3)
        + [
            LDI(r2, 3),
            JZ(r0, Label("argument_length")),
            JMP(Label("reject")),
            Label("argument_length"),
            CMPI(r3, 2),
            JFAIL(Label("reject")),
        ]
    )
    source += load(0) + [CMPLTI(r0, 2), JFAIL(Label("reject"))]
    source += load(1) + [JZ(r0, Label("reject")), CMPLTI(r0, 9), JFAIL(Label("reject"))]
    source += (
        load(136)
        + load(148, r3)
        + [
            XOR(r0, r3),
            LDI(r2, 4),
            JZ(r0, Label("input_matches")),
            JMP(Label("reject")),
            Label("input_matches"),
            JZ(r3, Label("reject")),
        ]
    )
    source += load(138) + [
        CMPLTI(r0, 65),
        JFAIL(Label("reject")),
        CMPLT(r0, r3),
        JFAIL(Label("valid")),
        JMP(Label("reject")),
        Label("valid"),
    ]
    source += load(148) + [LDI(r1, 150), STORE(r0, r1), LDI(r1, 160), STORE(r0, r1)]
    body = probe[probe.comment_index("Run-Test/Idle") :].split([Label("publish")], 1)[0]
    source += body + [Label("publish")] + probe.split([Label("publish")], 1)[1]
    source += [
        Label("reject"),
        LDI(r1, 147),
        STORE(r2, r1),
        LDI(r3, 0x11),
        Label("discard"),
        PREAD(r0, r3),
        JFAIL(Label("publish")),
        JMP(Label("discard")),
        Label("record_next"),
        PREAD(r0, r3),
        JMP(Label("request")),
    ]
    return source


if __name__ == "__main__":
    Path(__file__).with_name("jtag_runtime_candidate.asm").write_text(
        generate().to_asm()
    )
