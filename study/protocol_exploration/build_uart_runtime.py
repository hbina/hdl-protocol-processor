def load(address, reg=r0):
    return [LDI(r1, address), LOAD(reg, r1)]


def charge(amount, prefix, period, name):
    # r4:r5:r6 is remaining clocks. Every completed search path consumes
    # exactly32 clocks; a false-start path consumes256, including qualification.
    borrow_high = Fragment.choose(
        lambda t: JZ(r4, t), [LDI(r7, 1)], [ADDI(r4, 255), LDI(r5, 255)]
    )
    borrow_mid = Fragment.choose(lambda t: JZ(r5, t), borrow_high, [ADDI(r5, 255)])
    out = Fragment([LDI(r7, 0)])
    if amount == 32:
        out.add([CMPLTI(r6, 32), ADDI(r6, 224)])
        out.add(Fragment.choose(JFAIL, (), borrow_mid))
    else:
        assert amount == 256
        out.add(borrow_mid)
    out.add([MOV(r0, r4), OR(r0, r5), OR(r0, r6)])
    out.add(Fragment.choose(lambda t: JZ(r0, t), [LDI(r7, 1)]))
    out.add(Fragment.delay(period - prefix - out.cycles - 1))
    out.add([JZ(r7, Label("search")), Label(str(name)), LDI(r2, 6), JMP(Label("fail"))])
    return out.program


def generate():
    Fragment.serial = 0
    source = Program(
        [
            Comment(
                "GENERATED by build_uart_runtime.py. Generic eight-register model."
            ),
            Comment(
                "TX=uio0, RX=uio1;115200 baud at50MHz; r3=0xa5 only while RX armed."
            ),
            Comment(
                "Request128..143;event144..159;RX remaining160. Parameters[RXcount,windows,0,0]."
            ),
            SETO(1),
            SETOE(1),
            LDI(r3, 0),
            Label("idle"),
            LDI(r7, 0x22),
            PREAD(r0, r7),
            JFAIL(Label("idle")),
            LDI(r1, 128),
            LDI(r2, 16),
            Label("record"),
            STORE(r0, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label("record_next")),
            LDI(r1, 144),
            LDI(r2, 16),
            LDI(r0, 0),
            Label("clear_event"),
            STORE(r0, r1),
            ADDI(r1, 1),
            DJNZ(r2, Label("clear_event")),
        ]
    )
    for src, dst in [(128, 144), (129, 145)]:
        source += load(src) + [LDI(r1, dst), STORE(r0, r1)]
    source += [
        LDI(r0, 1),
        LDI(r1, 146),
        STORE(r0, r1),
        LDI(r7, 2),
        PREAD(r4, r7),
        LDI(r1, 148),
        STORE(r4, r1),
    ]
    source += load(131) + [
        LDI(r1, 140),
        LDI(r2, 4),
        Label("reserved"),
        LOAD(r4, r1),
        OR(r0, r4),
        ADDI(r1, 1),
        DJNZ(r2, Label("reserved")),
        LDI(r2, 1),
        JZ(r0, Label("record_high")),
        JMP(Label("reject")),
        Label("record_high"),
        LDI(r1, 133),
        LDI(r4, 4),
        Label("high_bytes"),
        LOAD(r5, r1),
        OR(r0, r5),
        ADDI(r1, 2),
        DJNZ(r4, Label("high_bytes")),
        JZ(r0, Label("operation")),
        JMP(Label("reject")),
        Label("operation"),
    ]
    source += load(130, r6) + [
        LDI(r2, 2),
        JZ(r6, Label("reject")),
        CMPLTI(r6, 4),
        JFAIL(Label("reject")),
    ]
    source += load(132) + [
        LDI(r2, 3),
        JZ(r0, Label("argument_length")),
        JMP(Label("reject")),
        Label("argument_length"),
    ]
    source += load(134) + [CMPI(r0, 4), JFAIL(Label("reject"))]
    source += (
        load(2)
        + load(3, r4)
        + [
            OR(r0, r4),
            JZ(r0, Label("timeout_argument")),
            JMP(Label("reject")),
            Label("timeout_argument"),
        ]
    )
    source += load(1) + [JZ(r0, Label("reject"))]
    source += (
        load(136)
        + load(148, r4)
        + [
            XOR(r0, r4),
            LDI(r2, 4),
            JZ(r0, Label("output_length")),
            JMP(Label("reject")),
            Label("output_length"),
        ]
    )
    source += load(138, r5) + [CMPLTI(r5, 65), JFAIL(Label("reject"))]
    source += load(0, r4) + [
        CMPLTI(r4, 65),
        JFAIL(Label("reject")),
        CMPI(r6, 1),
        JFAIL(Label("not_tx_only")),
        OR(r4, r5),
        JZ(r4, Label("transmit")),
        JMP(Label("reject")),
        Label("not_tx_only"),
        CMPLT(r5, r4),
        JFAIL(Label("output_enough")),
        JMP(Label("reject")),
        Label("output_enough"),
        CMPI(r6, 2),
        JFAIL(Label("transmit")),
    ]
    source += load(148) + [
        JZ(r0, Label("transmit")),
        JMP(Label("reject")),
        Label("transmit"),
    ]
    source += load(148, r1) + [
        LDI(r7, 0x11),
        JZ(r1, Label("receive")),
        Label("tx_byte"),
        PREAD(r0, r7),
        LDI(r2, 0),
        OUTBIT(r2, 0),
        LDI(r2, 8),
        WAIT(255),
        WAIT(175),
        Label("tx_bit"),
        OUTBIT(r0, 0),
        SHR(r0),
        WAIT(255),
        WAIT(174),
        DJNZ(r2, Label("tx_bit")),
        SETO(1),
        WAIT(255),
        WAIT(176),
        DJNZ(r1, Label("tx_byte")),
        Label("receive"),
    ]
    source += load(0) + [
        LDI(r1, 160),
        STORE(r0, r1),
        JZ(r0, Label("publish")),
        LDI(r3, 0xA5),
        LDI(r1, 0),
        JMP(Label("start_deadline")),
        Label("rx_byte"),
        LDI(r1, 1),
        Label("start_deadline"),
        LDI(r0, 1),
        LOAD(r4, r0),
        LDI(r5, 0),
        LDI(r6, 0),
        Label("search"),
        IN(r0),
        ANDI(r0, 2),
        JZ(r0, Label("low_line")),
        LDI(r1, 1),
        JMP(Label("poll_charge")),
        Label("low_line"),
        JZ(r1, Label("unqualified_low")),
        WAIT(209),
        IN(r0),
        ANDI(r0, 2),
        JZ(r0, Label("qualified")),
    ]
    source += charge(256, 217, 256, "false_start_timeout")
    source += [Label("unqualified_low"), NOP(), Label("poll_charge")] + charge(
        32, 5, 32, "poll_timeout"
    )
    source += [
        Label("qualified"),
        LDI(r0, 0),
        LDI(r1, 8),
        WAIT(255),
        WAIT(173),
        Label("rx_bit"),
        INBIT(r0, 1),
        ROR(r0),
        WAIT(255),
        WAIT(174),
        DJNZ(r1, Label("rx_bit")),
        IN(r1),
        ANDI(r1, 2),
        JZ(r1, Label("framing")),
        LDI(r7, 0x30),
        PWRITE(r0, r7),
        LDI(r0, 0),
        ADDI(r7, 1),
        PWRITE(r0, r7),
        ADDI(r7, 1),
        PWRITE(r0, r7),
        LDI(r1, 150),
        LOAD(r0, r1),
        ADDI(r0, 1),
        STORE(r0, r1),
        LDI(r1, 160),
        LOAD(r0, r1),
        ADDI(r0, 255),
        STORE(r0, r1),
        JZ(r0, Label("publish")),
        JMP(Label("rx_byte")),
        Label("framing"),
        LDI(r2, 7),
        Label("fail"),
        SETO(1),
        LDI(r3, 0),
        LDI(r1, 147),
        STORE(r2, r1),
        JMP(Label("publish")),
        Label("reject"),
        LDI(r1, 147),
        STORE(r2, r1),
        LDI(r7, 0x11),
        Label("discard"),
        PREAD(r0, r7),
        JFAIL(Label("publish")),
        JMP(Label("discard")),
        Label("publish"),
        LDI(r3, 0),
        LDI(r1, 144),
        LDI(r2, 16),
        LDI(r7, 0x40),
        Label("event"),
        LOAD(r0, r1),
        PWRITE(r0, r7),
        ADDI(r1, 1),
        DJNZ(r2, Label("event")),
        LDI(r7, 0x41),
        LDI(r0, 0),
        PWRITE(r0, r7),
        JMP(Label("idle")),
        Label("record_next"),
        PREAD(r0, r7),
        JMP(Label("record")),
    ]
    return source


if __name__ == "__main__":
    Path(__file__).with_name("uart_runtime_candidate.asm").write_text(
        generate().to_asm()
    )
