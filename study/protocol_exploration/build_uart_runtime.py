#!/usr/bin/env python3
"""Validated UART ABI with instruction-clock deadlines; no timer RTL."""

from pathlib import Path

from build_can_rx import Block


def load(address, reg="r0"):
    return f"LDI r1, {address}\nLOAD {reg}, r1\n"


def charge(amount, prefix, period, name):
    # r4:r5:r6 is remaining clocks. Every completed search path consumes
    # exactly32 clocks; a false-start path consumes256, including qualification.
    borrow_high = Block.choose("JZ r4", "LDI r7, 1", "ADDI r4, 255\nLDI r5, 255")
    borrow_mid = Block.choose("JZ r5", borrow_high, "ADDI r5, 255")
    out = Block("LDI r7, 0")
    if amount == 32:
        out.add("CMPLTI r6, 32\nADDI r6, 224")
        out.add(Block.choose("JFAIL", "", borrow_mid))
    else:
        assert amount == 256
        out.add(borrow_mid)
    out.add("MOV r0, r4\nOR r0, r5\nOR r0, r6")
    out.add(Block.choose("JZ r0", "LDI r7, 1"))
    out.add(Block.delay(period - prefix - out.cycles - 1))
    out.add(f"JZ r7, search\n{name}:\nLDI r2, 6\nJMP fail")
    return "\n".join(out.lines) + "\n"


