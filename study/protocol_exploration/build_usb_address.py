#!/usr/bin/env python3
"""USB bus reset and deferred SET_ADDRESS using only generic instructions."""

from pathlib import Path

from build_usb_control import generate as control_source


def token_crc_byte(address):
    crc = 31
    for bit in range(11):
        feedback = (crc ^ (address >> bit)) & 1
        crc = (crc >> 1) ^ (20 if feedback else 0)
    return (crc ^ 31) << 3


def generate():
    source = control_source()
    # Prefetch token address and replenish the idle budget in existing EOP
    # padding. The sample schedule is unchanged; token matching stays short.
    assert source.count("WAIT 25\n") == 1
    source = source.replace(
        "WAIT 25\n",
        "LDI r6, 155\nLOAD r6, r6\nLDI r1, 186\nLDI r0, 4\nSTORE r0, r1\nWAIT 18\n",
    )
    source = source.replace("LDI r0, 155\nLOAD r6, r0\nXOR r4, r6", "XOR r4, r6")
    source = source.replace(
        "CMPI r4, 0\nJFAIL ignore_token",
        "XOR r4, r6\nJZ r4, address_low_ok\nJMP ignore_token\naddress_low_ok:",
    )
    source = source.replace("idle_tick:\n", "idle_tick:\nJZ r0, reset_probe\n")
    source = source.replace("sop_tick:\n", "sop_tick:\nJZ r0, reset_probe\n")
    source = source.replace(
        "DJNZ r2, wait_idle\nJMP timeout", "DJNZ r2, wait_idle\nJMP idle_expired"
    )
    source = source.replace(
        "DJNZ r2, wait_sop\nJMP timeout", "DJNZ r2, wait_sop\nJMP idle_expired"
    )
    source = source.replace(
        "form_error:\nLDI r2, 17",
        "form_error:\nIN r0\nANDI r0, 3\nJZ r0, reset_probe\nLDI r2, 17",
    )
    source = source.replace(
        "STORE r1, r0\nJMP rearm\nrearm:",
        "STORE r1, r0\nLDI r0, 186\nLDI r1, 4\nSTORE r1, r0\nJMP rearm\nrearm:",
        1,
    )
    # SETUP dispatch for the standard, zero-data SET_ADDRESS request.
    marker = "CMPI r0, 0x2d\nJFAIL control_out_data\n"
    assert source.count(marker) == 1
    source = source.replace(
        marker,
        marker
        + """LDI r0, 145
LOAD r0, r0
CMPI r0, 0
JFAIL vendor_setup
LDI r0, 146
LOAD r0, r0
CMPI r0, 5
JFAIL unsupported
JMP setup_address
vendor_setup:
""",
    )
    source = source.replace(
        "maybe_read_in:\nCMPI r0, 3\nJFAIL rearm",
        "maybe_read_in:\nCMPI r0, 7\nJFAIL maybe_vendor_read\nJMP token_match\nmaybe_vendor_read:\nCMPI r0, 3\nJFAIL rearm",
    )
    source = source.replace(
        "ack_read_data:\nCMPI r1, 11\nJFAIL rearm",
        "ack_read_data:\nCMPI r1, 15\nJFAIL ack_vendor_read\nJMP commit_address\nack_vendor_read:\nCMPI r1, 11\nJFAIL rearm",
    )
    tail = """
setup_address:
LDI r0, 147
LOAD r4, r0
CMPLTI r4, 128
JFAIL form_error
LDI r0, 148
LOAD r1, r0
ADDI r0, 1
LOAD r2, r0
OR r1, r2
ADDI r0, 1
LOAD r2, r0
OR r1, r2
ADDI r0, 1
LOAD r2, r0
OR r1, r2
ADDI r0, 1
LOAD r2, r0
OR r1, r2
JZ r1, address_fields_ok
JMP form_error
address_fields_ok:
LDI r0, 175
STORE r4, r0
LDI r6, 16
"""
    for bit in range(7):
        delta = token_crc_byte(1 << bit) ^ token_crc_byte(0)
        tail += f"MOV r0, r4\nANDI r0, {1 << bit}\nJZ r0, address_bit_{bit}\nXORI r6, {delta}\naddress_bit_{bit}:\n"
    tail += """LDI r0, 176
STORE r6, r0
LDI r0, 182
LDI r1, 0
STORE r1, r0
LDI r0, 160
LDI r1, 0x4b
STORE r1, r0
LDI r0, 171
LDI r1, 7
STORE r1, r0
JMP control_ack
commit_address:
LDI r0, 175
LOAD r1, r0
LDI r0, 155
STORE r1, r0
LDI r0, 176
LOAD r1, r0
LDI r0, 156
STORE r1, r0
LDI r0, 171
LDI r1, 0
STORE r1, r0
JMP rearm
idle_expired:
LDI r0, 186
LOAD r1, r0
ADDI r1, 255
STORE r1, r0
JZ r1, timeout
LDI r2, 0
LDI r3, 0
JMP wait_idle
reset_probe:
LDI r4, 40
reset_filter:
IN r0
ANDI r0, 3
JZ r0, reset_zero
JMP rearm
reset_zero:
DJNZ r4, reset_filter
reset_confirmed:
SETO 56
LDI r1, 0
LDI r0, 155
STORE r1, r0
LDI r0, 157
STORE r1, r0
LDI r0, 171
STORE r1, r0
ADDI r0, 1
STORE r1, r0
LDI r0, 175
STORE r1, r0
LDI r0, 182
STORE r1, r0
LDI r0, 156
LDI r1, 16
STORE r1, r0
LDI r0, 176
STORE r1, r0
LDI r0, 158
LDI r1, 32
STORE r1, r0
LDI r0, 186
LDI r1, 4
STORE r1, r0
reset_release:
IN r0
ANDI r0, 3
JZ r0, reset_release
JMP rearm
"""
    return (source + tail).replace(
        "# GENERATED by build_usb_control.py.", "# GENERATED by build_usb_address.py."
    )


if __name__ == "__main__":
    Path(__file__).with_name("usb_address_candidate.asm").write_text(generate())
