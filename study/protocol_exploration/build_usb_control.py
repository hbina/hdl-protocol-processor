#!/usr/bin/env python3
"""Autonomous single-packet vendor control write/read pair, generic ISA only."""

from pathlib import Path

from build_usb_stream import generate as stream_source


def generate():
    source = stream_source().replace(
        "LDI r0, 16\nSTORE r0, r4", "LDI r0, 32\nSTORE r0, r4"
    )
    old = "LDI r0, 40\nLOAD r0, r0\nJZ r0, rearm\nJMP prepare_tx"
    assert source.count(old) == 1
    source = source.replace(
        old,
        """LDI r0, 171
LDI r1, 0
STORE r1, r0
ADDI r0, 1
STORE r1, r0
JMP rearm""",
    )
    source = source.replace(
        "tx_packet:\nLDI r0, 185\nLDI r1, 1\nSTORE r1, r0",
        "tx_packet:\nLDI r0, 171\nLOAD r1, r0\nORI r1, 8\nSTORE r1, r0",
    )
    start = source.index("LDI r0, 40\n", source.index("length_ok:"))
    end = source.index("out_gate:\n", start)
    source = (
        source[:start]
        + """CMPI r5, 0x2d
JFAIL control_maybe_out
JMP control_token_match
control_maybe_out:
CMPI r5, 0xe1
JFAIL control_maybe_ack
JMP control_token_match
control_maybe_ack:
CMPI r5, 0xd2
JFAIL control_in_gate
CMPI r7, 145
JFAIL rearm
LDI r0, 171
LOAD r1, r0
CMPI r1, 10
JFAIL ack_read_data
LDI r1, 4
STORE r1, r0
JMP rearm
ack_read_data:
CMPI r1, 11
JFAIL rearm
LDI r1, 5
STORE r1, r0
JMP rearm
control_in_gate:
CMPI r5, 0x69
JFAIL out_gate
LDI r0, 171
LOAD r0, r0
ANDI r0, 7
CMPI r0, 2
JFAIL maybe_read_in
JMP token_match
maybe_read_in:
CMPI r0, 3
JFAIL rearm
JMP token_match
"""
        + source[end:]
    )
    old = "valid:\nLDI r0, 0\nLOAD r0, r0\nJZ r0, output\nWAIT 65"
    assert source.count(old) == 1
    source = source.replace(
        old,
        """valid:
LDI r0, 136
LOAD r0, r0
CMPI r0, 0x2d
JFAIL control_out_data
LDI r0, 152
LOAD r0, r0
JZ r0, setup_length_low
JMP form_error
setup_length_low:
LDI r0, 151
LOAD r4, r0
CMPLTI r4, 9
JFAIL form_error
JZ r4, form_error
LDI r0, 145
LOAD r0, r0
CMPI r0, 0x40
JFAIL setup_read
LDI r0, 146
LOAD r0, r0
CMPI r0, 1
JFAIL unsupported
LDI r0, 174
STORE r4, r0
LDI r0, 171
LDI r1, 1
STORE r1, r0
JMP control_ack
setup_read:
CMPI r0, 0xc0
JFAIL unsupported
LDI r0, 146
LOAD r0, r0
CMPI r0, 2
JFAIL unsupported
LDI r0, 171
LOAD r0, r0
CMPI r0, 4
JFAIL unsupported
LDI r0, 172
LOAD r0, r0
XOR r0, r4
JZ r0, read_length_ok
JMP form_error
read_length_ok:
LDI r0, 182
STORE r4, r0
LDI r0, 171
LDI r1, 3
STORE r1, r0
JMP control_ack
control_out_data:
CMPI r5, 0x4b
JFAIL pid_error
LDI r0, 171
LOAD r0, r0
CMPI r0, 1
JFAIL control_read_status
MOV r2, r7
ADDI r2, 109
LDI r0, 174
LOAD r4, r0
XOR r4, r2
JZ r4, write_length_ok
JMP form_error
write_length_ok:
LDI r0, 172
STORE r2, r0
LDI r1, 145
LDI r3, 161
copy_control_payload:
LOAD r0, r1
STORE r0, r3
ADDI r1, 1
ADDI r3, 1
DJNZ r2, copy_control_payload
LDI r0, 182
LDI r1, 0
STORE r1, r0
LDI r0, 171
LDI r1, 2
STORE r1, r0
LDI r0, 160
LDI r1, 0x4b
STORE r1, r0
JMP control_ack
control_read_status:
ANDI r0, 7
CMPI r0, 2
JFAIL not_duplicate_write
JMP control_ack
not_duplicate_write:
CMPI r0, 5
JFAIL unsupported
CMPI r7, 147
JFAIL form_error
LDI r0, 171
LDI r1, 6
STORE r1, r0
control_ack:
WAIT 10""",
    )
    # DATA PID in r5 was overwritten during CRC syndrome validation. Re-read.
    source = source.replace(
        "control_out_data:\nCMPI r5, 0x4b",
        "control_out_data:\nLDI r0, 144\nLOAD r5, r0\nCMPI r5, 0x4b",
    )
    start = source.index("output:\n")
    end = source.index("timeout:\n", start)
    source = (
        source[:start]
        + """output:
LDI r0, 171
LOAD r0, r0
CMPI r0, 6
JFAIL rearm
LDI r0, 172
LOAD r2, r0
LDI r0, 134
STORE r2, r0
LDI r1, 161
control_result_byte:
LOAD r0, r1
LDI r3, 0x30
PWRITE r0, r3
LDI r0, 0
ADDI r3, 1
PWRITE r0, r3
ADDI r3, 1
PWRITE r0, r3
ADDI r1, 1
DJNZ r2, control_result_byte
JMP publish
"""
        + source[end:]
    )
    # Address0/endpoint0 is the selected scope of this control probe. Token
    # dispatch precedes handshake dispatch to preserve minimum token/DATA gap.
    source += """
control_token_match:
CMPI r7, 147
JFAIL ignore_token
LDI r0, 145
LOAD r4, r0
CMPI r4, 0
JFAIL ignore_token
LDI r0, 146
LOAD r4, r0
LDI r0, 156
LOAD r6, r0
XOR r4, r6
JZ r4, control_token_valid
JMP ignore_token
control_token_valid:
LDI r0, 157
STORE r5, r0
JMP rearm
"""
    return source.replace(
        "# GENERATED by build_usb_stream.py.", "# GENERATED by build_usb_control.py."
    )


if __name__ == "__main__":
    Path(__file__).with_name("usb_control_candidate.asm").write_text(generate())
