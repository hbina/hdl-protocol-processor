#!/usr/bin/env python3
"""Compact live USB firmware using generic carry shifts and leaf subroutines."""

from pathlib import Path

from fragments import Fragment
from build_usb_live import generate as live_source
from tools.isa import JNC
from tools.isa import (
    ADDI,
    ANDI,
    CALL,
    CMPI,
    CMPLTI,
    DJNZ,
    IN,
    JFAIL,
    JMP,
    JZ,
    LDI,
    Label,
    MOV,
    NOP,
    ORI,
    RET,
    RRC,
    SHR,
    SHRC,
    STORE,
    WAIT,
    XOR,
    XORI,
    r0,
    r1,
    r2,
    r3,
    r4,
    r5,
    r6,
    r7,
)
from tools.program import Comment


def generate():
    Fragment.serial = 300
    old = live_source()
    prefix = old.split([Label("bit_0_0")], 1)[0]
    prefix = prefix.replace([JMP(Label("bit_0_2"))], [JMP(Label("sample_2"))])
    prefix = prefix.replace([LDI(r4, 0)], [LDI(r4, 0), LDI(r5, 8)])
    prefix = prefix.replace([WAIT(5)], [WAIT(4)])
    suffix = old.split([Label("eop")], 1)[1]
    suffix = suffix.replace(
        [CMPI(r6, 6)], [CMPI(r5, 8), JFAIL(Label("form_error")), CMPI(r6, 6)], 1
    )
    suffix = suffix.replace([WAIT(27)], [WAIT(25)], 1)
    tail = [Label("failure")] + suffix.split([Label("failure")], 1)[1]
    suffix = suffix.split([Label("crc_update")], 1)[0]
    out = Fragment(
        [Comment("GENERATED by build_usb_dense.py. Isolated generic-carry model only.")]
    )
    out.add(prefix)
    for phase, period in enumerate([33, 33, 34]):
        out.add(
            [
                Label(f"sample_{phase}"),
                IN(r0),
                ANDI(r0, 3),
                JZ(r0, Label("eop")),
                CALL(Label("receive_bit")),
                JZ(r0, Label(f"normal_{phase}")),
            ]
        )
        # Stuffed cell: sample3+CALL1+body11+JZ1 =16 clocks.
        out.add(Fragment.delay(period - 16 - 1)).add(
            [JMP(Label(f"sample_{(phase + 1) % 3}"))]
        )
        out.add(
            [
                Label(f"normal_{phase}"),
                CMPLTI(r7, 155),
                JFAIL(Label("overflow")),
                DJNZ(r5, Label(f"no_byte_{phase}")),
                STORE(r4, r7),
                ADDI(r7, 1),
                LDI(r5, 8),
            ]
        )
        # Normal byte boundary:3+CALL1+body19+JZ1+guard2+DJNZ1+store4=31.
        out.add(Fragment.delay(period - 31 - 1)).add(
            [JMP(Label(f"sample_{(phase + 1) % 3}"))]
        )
        out.add([Label(f"no_byte_{phase}")])
        out.add(Fragment.delay(period - 27 - 1)).add(
            [JMP(Label(f"sample_{(phase + 1) % 3}"))]
        )
    out.add([Label("eop")] + suffix)
    out.add(
        [
            Label("receive_bit"),
            XOR(r1, r0),
            CMPI(r1, 0),
            JFAIL(Label("zero")),
            MOV(r1, r0),
            CMPI(r6, 6),
            JFAIL(Label("one_ok")),
            JMP(Label("stuff_error")),
            Label("one_ok"),
            ADDI(r6, 1),
            SHR(r4),
            ORI(r4, 128),
            XORI(r2, 1),
            JMP(Label("crc_step")),
            Label("zero"),
            CMPI(r1, 3),
            JFAIL(Label("form_error")),
            MOV(r1, r0),
            CMPI(r6, 6),
            LDI(r6, 0),
            JFAIL(Label("zero_data")),
            LDI(r0, 1),
            RET(),
            Label("zero_data"),
            SHR(r4),
            NOP(),
            Label("crc_step"),
            SHRC(r3),
            RRC(r2),
        ]
    )
    out.add(Fragment.choose(JNC, (), [XORI(r2, 1), XORI(r3, 160)]))
    out.add([LDI(r0, 0), RET()]).add(tail)
    return out.program


if __name__ == "__main__":
    Path(__file__).with_name("usb_dense_candidate.asm").write_text(generate().to_asm())
