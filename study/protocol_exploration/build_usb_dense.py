#!/usr/bin/env python3
"""Compact live USB firmware using generic carry shifts and leaf subroutines."""

from pathlib import Path

from build_can_rx import Block
from build_usb_live import generate as live_source


def generate():
    Block.serial = 300
    old = live_source()
    prefix = old.split("bit_0_0:\n", 1)[0]
    prefix = prefix.replace("JMP bit_0_2", "JMP sample_2")
    prefix = prefix.replace("LDI r4, 0\n", "LDI r4, 0\nLDI r5, 8\n")
    prefix = prefix.replace("WAIT 5\n", "WAIT 4\n")
    suffix = old.split("eop:\n", 1)[1]
    suffix = suffix.replace(
        "CMPI r6, 6\n", "CMPI r5, 8\nJFAIL form_error\nCMPI r6, 6\n", 1
    )
    suffix = suffix.replace("WAIT 27\n", "WAIT 25\n", 1)
    tail = "failure:\n" + suffix.split("failure:\n", 1)[1]
    suffix = suffix.split("crc_update:\n", 1)[0]
    out = Block("# GENERATED by build_usb_dense.py. Isolated generic-carry model only.")
    out.add(prefix)
    for phase, period in enumerate([33, 33, 34]):
        out.add(f"""
sample_{phase}:
    IN r0
    ANDI r0, 3
    JZ r0, eop
    CALL receive_bit
    JZ r0, normal_{phase}
    """)
        # Stuffed cell: sample3+CALL1+body11+JZ1 =16 clocks.
        out.add(Block.delay(period - 16 - 1)).add(f"JMP sample_{(phase + 1) % 3}")
        out.add(f"""
normal_{phase}:
    CMPLTI r7, 155
    JFAIL overflow
    DJNZ r5, no_byte_{phase}
    STORE r4, r7
    ADDI r7, 1
    LDI r5, 8
    """)
        # Normal byte boundary:3+CALL1+body19+JZ1+guard2+DJNZ1+store4=31.
        out.add(Block.delay(period - 31 - 1)).add(f"JMP sample_{(phase + 1) % 3}")
        out.add(f"no_byte_{phase}:")
        out.add(Block.delay(period - 27 - 1)).add(f"JMP sample_{(phase + 1) % 3}")
    out.add("eop:\n" + suffix)
    out.add("""
receive_bit:
    XOR r1, r0
    CMPI r1, 0
    JFAIL zero
    MOV r1, r0
    CMPI r6, 6
    JFAIL one_ok
    JMP stuff_error
one_ok:
    ADDI r6, 1
    SHR r4
    ORI r4, 128
    XORI r2, 1
    JMP crc_step
zero:
    CMPI r1, 3
    JFAIL form_error
    MOV r1, r0
    CMPI r6, 6
    LDI r6, 0
    JFAIL zero_data
    LDI r0, 1
    RET
zero_data:
    SHR r4
    NOP
crc_step:
    SHRC r3
    RRC r2
    """)
    out.add(Block.choose("JNC", "", "XORI r2, 1\nXORI r3, 160"))
    out.add("LDI r0, 0\nRET").add(tail)
    return "\n".join(out.lines) + "\n"


if __name__ == "__main__":
    Path(__file__).with_name("usb_dense_candidate.asm").write_text(generate())
