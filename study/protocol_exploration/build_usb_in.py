#!/usr/bin/env python3
"""Combined OUT/SETUP and IN packet probe; all USB semantics are firmware."""

from pathlib import Path

from build_can_rx import Block
from build_usb_out import generate as out_source


def generate():
    source = out_source()
    old = "LDI r2, 14\nrecord:\nPREAD r0, r3\nDJNZ r2, record"
    assert source.count(old) == 1
    source = source.replace(
        old,
        """
LDI r2, 6
record:
PREAD r0, r3
DJNZ r2, record
PREAD r0, r3
LDI r1, 182
STORE r0, r1
LDI r2, 7
record_tail:
PREAD r0, r3
DJNZ r2, record_tail
""",
    )
    # Preparing TX leaves the address/CRC5 token body intact. RX uses144..154,
    # TX packet159..170, counters181..185, packed waveform192..220(max29B).
    marker = "rearm:\nLDI r2, 0"
    assert source.count(marker) == 1
    source = source.replace(
        marker,
        """
LDI r0, 185
LDI r1, 0
STORE r1, r0
LDI r0, 40
LOAD r0, r0
JZ r0, rearm
JMP prepare_tx
rearm:
LDI r2, 0
""",
    )
    source = source.replace(
        "CMPLTI r7, 147\nJFAIL length_ok", "CMPLTI r7, 145\nJFAIL length_ok"
    )
    marker = "length_ok:\nLDI r0, 144\nLOAD r5, r0"
    source = source.replace(
        marker,
        marker
        + """
LDI r0, 40
LOAD r0, r0
JZ r0, out_gate
CMPI r5, 0xd2
JFAIL in_gate
CMPI r7, 145
JFAIL rearm
LDI r0, 185
LOAD r0, r0
JZ r0, rearm
LDI r0, 0x69
LDI r1, 136
STORE r0, r1
JMP publish
in_gate:
CMPI r5, 0x69
JFAIL rearm
JMP token_match
out_gate:
CMPLTI r7, 147
JFAIL out_length_ok
JMP rearm
out_length_ok:
""",
    )
    source = source.replace(
        "token_valid:\nLDI r0, 157",
        "token_valid:\nCMPI r5, 0x69\nJFAIL out_token_valid\nJMP tx_packet\nout_token_valid:\nLDI r0, 157",
    )
    # Entire precomputation is before reception, never on an IN response path.
    tail = Block("""
prepare_tx:
LDI r0, 182
LOAD r6, r0
CMPLTI r6, 9
JFAIL form_error
LDI r0, 39
LOAD r4, r0
CMPI r4, 0xc3
JFAIL check_tx_data1
JMP tx_pid_valid
check_tx_data1:
CMPI r4, 0x4b
JFAIL pid_error
tx_pid_valid:
LDI r0, 160
STORE r4, r0
LDI r7, 161
LDI r2, 255
LDI r3, 255
JZ r6, tx_crc_done
tx_payload:
LDI r0, 0x11
PREAD r4, r0
STORE r4, r7
ADDI r7, 1
XOR r2, r4
LDI r5, 8
tx_crc_bit:
SHRC r3
RRC r2
JNC tx_crc_no_xor
XORI r2, 1
XORI r3, 160
tx_crc_no_xor:
DJNZ r5, tx_crc_bit
DJNZ r6, tx_payload
tx_crc_done:
XORI r2, 255
XORI r3, 255
STORE r2, r7
ADDI r7, 1
STORE r3, r7
LDI r0, 159
LDI r1, 128
STORE r1, r0
LDI r0, 183
LDI r1, 159
STORE r1, r0
LDI r0, 182
LOAD r1, r0
ADDI r1, 4
LDI r0, 184
STORE r1, r0
LDI r7, 192
LDI r6, 0
LDI r5, 4
LDI r4, 2
LDI r3, 0
encode_byte:
LDI r0, 183
LOAD r1, r0
LOAD r1, r1
LDI r2, 8
encode_bit:
SHRC r1
JNC encode_zero
ADDI r3, 1
JMP encode_line
encode_zero:
XORI r4, 3
LDI r3, 0
encode_line:
CALL pack_line
CMPI r3, 6
JFAIL no_tx_stuff
XORI r4, 3
LDI r3, 0
CALL pack_line
no_tx_stuff:
DJNZ r2, encode_bit
LDI r0, 183
LOAD r1, r0
ADDI r1, 1
STORE r1, r0
LDI r0, 184
LOAD r1, r0
ADDI r1, 255
STORE r1, r0
JZ r1, encode_eop
JMP encode_byte
encode_eop:
LDI r4, 0
CALL pack_line
CALL pack_line
LDI r4, 2
CALL pack_line
MOV r0, r7
ADDI r0, 64
SHL r0
SHL r0
MOV r1, r5
XORI r1, 255
ADDI r1, 5
OR r0, r1
LDI r1, 181
STORE r0, r1
CMPI r5, 4
JFAIL pack_partial
JMP rearm
pack_partial:
SHR r6
SHR r6
DJNZ r5, pack_partial
STORE r6, r7
JMP rearm
pack_line:
SHR r6
SHR r6
MOV r0, r4
ROR r0
ROR r0
OR r6, r0
DJNZ r5, packed
STORE r6, r7
ADDI r7, 1
LDI r5, 4
packed:
RET
tx_packet:
LDI r0, 185
LDI r1, 1
STORE r1, r0
LDI r0, 181
LOAD r6, r0
LDI r1, 192
LOAD r2, r1
LDI r3, 4
MOV r0, r2
ANDI r0, 3
SHL r0
SHL r0
ORI r0, 32
WAIT 20
JMP tx_cell_0
""")
    for phase, period in enumerate([33, 33, 34]):
        tail.add(
            f"tx_cell_{phase}:\nOUT r0\nDJNZ r6, tx_more_{phase}\nJMP tx_finish_{phase}\ntx_more_{phase}:\nSHR r2\nSHR r2"
        )
        tail.add(Block.choose("DJNZ r3,", "", "ADDI r1, 1\nLOAD r2, r1\nLDI r3, 4"))
        tail.add("MOV r0, r2\nANDI r0, 3\nSHL r0\nSHL r0\nORI r0, 32")
        tail.add(Block.delay(period - 16)).add(f"JMP tx_cell_{(phase + 1) % 3}")
        tail.add(f"tx_finish_{phase}:").add(Block.delay(period - 3))
        tail.add("SETO 56\nJMP rearm")
    source += "\n".join(tail.lines) + "\n"
    source = source.replace(
        "# GENERATED by build_usb_out.py.", "# GENERATED by build_usb_in.py."
    )
    return (
        "\n".join(line.strip() for line in source.splitlines() if line.strip()) + "\n"
    )


if __name__ == "__main__":
    Path(__file__).with_name("usb_in_candidate.asm").write_text(generate())
