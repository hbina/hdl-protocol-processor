#!/usr/bin/env python3
"""Live USB packet decoder/CRC firmware for the generic call frontier model.

No addressed USB transaction state yet. Fixed CRC syndromes compensate for
including PID in the live CRC, avoiding a special-case instruction on each bit.
"""

import json
from pathlib import Path

from build_can_rx import Block
from build_usb_rx import generate as baseline_source


def crc(payload):
    value = 0xFFFF
    for byte in payload:
        value ^= byte
        for _ in range(8):
            value = (value >> 1) ^ (0xA001 if value & 1 else 0)
    return value


def constants():
    table = []
    for pid in [0xC3, 0x4B]:
        for length in range(9):
            payload = bytes(length)
            check = (crc(payload) ^ 0xFFFF).to_bytes(2, "little")
            value = crc(bytes([pid]) + payload + check)
            table += [value & 255, value >> 8]
    return table


def crc_body():
    block = Block("""
    MOV r0, r2
    ANDI r0, 1
    ROR r3
    MOV r5, r3
    ANDI r5, 128
    ANDI r3, 127
    SHR r2
    OR r2, r5
    """)
    block.add(Block.choose("JZ r0", "", "XORI r2, 1\nXORI r3, 160"))
    assert block.cycles == 12
    return block


def generate(use_calls=True):
    Block.serial = 200
    baseline = baseline_source()
    prefix = baseline.split("LDI r2, 0\nLDI r3, 0\nwait_idle:", 1)[0]
    prefix = "\n".join(line for line in prefix.splitlines() if not line.startswith("#"))
    footer = baseline.split("failure:\n", 1)[1]
    out = Block("# GENERATED by build_usb_live.py. Isolated generic-call model only.")
    out.add(prefix)
    out.add("""
    LDI r2, 0
    LDI r3, 0
wait_idle:
    IN r0
    ANDI r0, 3
    CMPI r0, 2
    JFAIL idle_tick
    JMP wait_sop
idle_tick:
    DJNZ r3, wait_idle
    DJNZ r2, wait_idle
    JMP timeout
wait_sop:
    IN r0
    ANDI r0, 3
    CMPI r0, 1
    JFAIL sop_tick
    LDI r1, 1
    LDI r2, 255
    LDI r3, 255
    LDI r4, 0
    LDI r6, 1
    LDI r7, 144
    WAIT 5
    """)
    periods = [33, 33, 34]
    for index, expected in enumerate([1, 2, 1, 2, 1, 2, 1, 1]):
        out.add(f"IN r0\nANDI r0, 3\nCMPI r0, {expected}\nJFAIL form_error")
        out.add(Block.delay(periods[index % 3] - 4 - (1 if index == 7 else 0)))
    out.add("JMP bit_0_2")
    out.add("sop_tick:\nDJNZ r3, wait_sop\nDJNZ r2, wait_sop\nJMP timeout")
    for bit in range(8):
        for phase, period in enumerate(periods):
            label = f"{bit}_{phase}"
            end = "eop" if bit == 0 else "form_error"
            out.add(f"""
bit_{label}:
    IN r0
    ANDI r0, 3
    JZ r0, {end}
    XOR r1, r0
    CMPI r1, 0
    JFAIL zero_{label}
    MOV r1, r0
    CMPI r6, 6
    JFAIL one_ok_{label}
    JMP stuff_error
one_ok_{label}:
    ADDI r6, 1
    SHR r4
    ORI r4, 128
    XORI r2, 1
    JMP crc_{label}
zero_{label}:
    CMPI r1, 3
    JFAIL form_error
    MOV r1, r0
    CMPI r6, 6
    LDI r6, 0
    JFAIL zero_data_{label}
    JMP stuffed_{label}
zero_data_{label}:
    SHR r4
    NOP
crc_{label}:
    """)
            # Both real-data paths arrive14 clocks after sampling. Bit0 can
            # check capacity here; terminal EOP bypasses this check entirely.
            extra = 0
            if bit == 0:
                out.add("CMPLTI r7, 155\nJFAIL overflow")
                extra += 2
            if use_calls:
                out.add("CALL crc_update")
                crc_cycles = 14  # CALL1 + body12 + RET1.
            else:
                out.add(crc_body())
                crc_cycles = 12
            if bit == 7:
                out.add("STORE r4, r7\nADDI r7, 1")
                extra += 3
            out.add(Block.delay(period - 14 - crc_cycles - extra - 1))
            out.add(f"JMP bit_{(bit + 1) % 8}_{(phase + 1) % 3}")
            out.add(f"stuffed_{label}:")
            out.add(Block.delay(period - 13 - 1))
            out.add(f"JMP bit_{bit}_{(phase + 1) % 3}")
    out.add("""
eop:
    # At byte boundary only. SE0 begins3 clocks before entry; validate at
    # approximately one and two bit times after the first sample.
    CMPI r6, 6
    JFAIL eop_not_stuff
    JMP stuff_error
eop_not_stuff:
    WAIT 27
    IN r0
    ANDI r0, 3
    CMPI r0, 0
    JFAIL form_error
    WAIT 28
    IN r0
    ANDI r0, 3
    CMPI r0, 2
    JFAIL form_error
    CMPLTI r7, 147
    JFAIL length_ok
    JMP form_error
length_ok:
    LDI r0, 144
    LOAD r5, r0
    MOV r0, r5
    SHR r0
    SHR r0
    SHR r0
    SHR r0
    XOR r0, r5
    ANDI r0, 15
    CMPI r0, 15
    JFAIL pid_error
    MOV r0, r7
    ADDI r0, 109
    SHL r0
    ADDI r0, 1
    CMPI r5, 0xc3
    JFAIL maybe_data1
    JMP syndrome
maybe_data1:
    CMPI r5, 0x4b
    JFAIL unsupported
    ADDI r0, 18
syndrome:
    # Argument bytes1..36 are a static firmware constant table, independent
    # of transaction payload, correcting CRC for the extra PID prefix.
    LOAD r5, r0
    XOR r5, r2
    JZ r5, high_crc
    JMP crc_error
high_crc:
    ADDI r0, 1
    LOAD r5, r0
    XOR r5, r3
    JZ r5, valid
    JMP crc_error
valid:
    LDI r0, 0
    LOAD r0, r0
    JZ r0, output
    WAIT 65
    """)
    for index, state in enumerate(
        [1, 2, 1, 2, 1, 2, 1, 1, 2, 2, 1, 2, 2, 1, 1, 1, 0, 0, 2]
    ):
        out.add(f"SETO {32 + (state << 2)}").add(Block.delay(periods[index % 3] - 1))
    out.add("""
    SETO 56
output:
    MOV r2, r7
    ADDI r2, 112
    MOV r0, r2
    LDI r1, 134
    STORE r0, r1
    LDI r1, 144
output_byte:
    LOAD r0, r1
    LDI r3, 0x30
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r1, 1
    DJNZ r2, output_byte
    JMP publish
timeout:
    LDI r2, 6
    JMP failure
crc_error:
    LDI r2, 16
    JMP failure
form_error:
    LDI r2, 17
    JMP failure
unsupported:
    LDI r2, 18
    JMP failure
stuff_error:
    LDI r2, 19
    JMP failure
overflow:
    LDI r2, 20
    JMP failure
pid_error:
    LDI r2, 21
    JMP failure
    """)
    if use_calls:
        out.add("crc_update:").add(crc_body()).add("RET")
    out.add("failure:\n").add(footer)
    return "\n".join(out.lines) + "\n"


if __name__ == "__main__":
    here = Path(__file__).parent
    (here / "usb_live_candidate.asm").write_text(generate())
    (here / "usb_live_inline_candidate.asm").write_text(generate(False))
    (here / "usb_live_constants.json").write_text(
        json.dumps({"syndrome_table": constants()}, indent=2) + "\n"
    )
