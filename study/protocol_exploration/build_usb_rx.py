#!/usr/bin/env python3
"""Low-speed USB packet capture/validation and ACK-latency experiment.

No USB engine or instruction is added. This packet probe is deliberately not
an enumerating USB device: its buffered decode/CRC path must be measured before
it can be used for transaction responses.
"""

from pathlib import Path

from fragments import Fragment
from build_can_rx import generate as request_template
from tools.isa import (
    ADDI,
    ANDI,
    CMPI,
    CMPLTI,
    DJNZ,
    IN,
    JFAIL,
    JMP,
    JZ,
    LDI,
    LOAD,
    Label,
    MOV,
    OR,
    PWRITE,
    ROR,
    SETO,
    SETOE,
    SHR,
    STORE,
    WAIT,
    XOR,
    XORI,
    r0,
    r1,
    r2,
    r3,
)
from tools.program import Comment


def generate():
    # Share the known request/event ABI source, without changing its baseline.
    source = request_template()
    prefix = source.split([LDI(r1, 242)], 1)[0]
    prefix = prefix.replace([SETO(1), SETOE(1)], [SETO(56), SETOE(60)])
    footer = source.split([Label("failure")], 1)[1].replace([SETO(1)], [SETO(56)])
    out = Fragment(
        [
            Comment(
                "GENERATED by build_usb_rx.py. Packet experiment; NOT a USB device."
            ),
            Comment("TUSB1106: uio0=VP,1=VM,2=VPO,3=VMO,4=OE_n,5=SOFTCON."),
            Comment("SPEED/SUSPND strapped low. No analog pads or protocol-aware RTL."),
            Comment(
                "param[0]=0 passive,1 emit diagnostic ACK after buffered validation."
            ),
            Comment(
                "Event128..143; raw states144..249 then bytes144..154; state250..255."
            ),
        ]
    )
    # Drop inherited receive-only comments; retain the request handling.
    out.add(prefix.without_comments())
    out.add(
        [
            LDI(r2, 0),
            LDI(r3, 0),
            Label("wait_idle"),
            IN(r0),
            ANDI(r0, 3),
            CMPI(r0, 2),
            JFAIL(Label("idle_tick")),
            JMP(Label("wait_sop")),
            Label("idle_tick"),
            DJNZ(r3, Label("wait_idle")),
            DJNZ(r2, Label("wait_idle")),
            JMP(Label("timeout")),
            Label("wait_sop"),
            IN(r0),
            ANDI(r0, 3),
            CMPI(r0, 1),
            JFAIL(Label("sop_tick")),
            LDI(r1, 144),
            WAIT(10),
        ]
    )
    periods = [33, 33, 34]
    for index, expected in enumerate([1, 2, 1, 2, 1, 2, 1, 1]):
        out.add(
            [
                Label(f"sync_{index}"),
                IN(r0),
                ANDI(r0, 3),
                CMPI(r0, expected),
                JFAIL(Label("form_error")),
            ]
        )
        out.add(Fragment.delay(periods[index % 3] - 4 - (1 if index == 7 else 0)))
    out.add([JMP(Label("capture_0"))])
    out.add(
        [
            Label("sop_tick"),
            DJNZ(r3, Label("wait_sop")),
            DJNZ(r2, Label("wait_sop")),
            JMP(Label("timeout")),
        ]
    )
    # Next global bit index8 has the34-clock phase. Capture to RAM is fast;
    # NRZI, destuffing and CRC are initially measured as buffered software.
    capture_periods = [34, 33, 33]
    for index, period in enumerate(capture_periods):
        out.add(
            [
                Label(f"capture_{index}"),
                IN(r0),
                ANDI(r0, 3),
                STORE(r0, r1),
                ADDI(r1, 1),
                JZ(r0, Label(f"eop_{index}")),
                CMPI(r1, 250),
                JFAIL(Label(f"room_{index}")),
                JMP(Label("overflow")),
                Label(f"room_{index}"),
            ]
        )
        out.add(Fragment.delay(period - 8 - 1)).add(
            [JMP(Label(f"capture_{(index + 1) % 3}"))]
        )
    for index, period in enumerate(capture_periods):
        out.add(
            [
                Label(f"eop_{index}"),
                MOV(r0, r1),
                ADDI(r0, 255),
                LDI(r1, 250),
                STORE(r0, r1),
            ]
        )
        out.add(Fragment.delay(period - 11))
        out.add([IN(r0), ANDI(r0, 3), CMPI(r0, 0), JFAIL(Label("form_error"))])
        out.add(Fragment.delay(capture_periods[(index + 1) % 3] - 4))
        out.add(
            [
                IN(r0),
                ANDI(r0, 3),
                CMPI(r0, 2),
                JFAIL(Label("form_error")),
                JMP(Label("decode")),
            ]
        )
    out.add(
        [
            Label("decode"),
            LDI(r1, 250),
            LOAD(r0, r1),
            CMPI(r0, 144),
            JFAIL(Label("decode_nonempty")),
            JMP(Label("form_error")),
            Label("decode_nonempty"),
            Comment(
                "State250=exclusive raw end,251=bits left,252=byte,253=byte write ptr,"
            ),
            Comment(
                "254=raw read ptr,255=decoded bit. Decode behind the raw read cursor."
            ),
            LDI(r0, 8),
            LDI(r1, 251),
            STORE(r0, r1),
            ADDI(r1, 1),
            LDI(r0, 0),
            STORE(r0, r1),
            ADDI(r1, 1),
            LDI(r0, 144),
            STORE(r0, r1),
            ADDI(r1, 1),
            STORE(r0, r1),
            LDI(r2, 1),
            LDI(r3, 1),
            Label("raw_bit"),
            LDI(r1, 254),
            LOAD(r1, r1),
            LOAD(r0, r1),
            CMPI(r0, 3),
            JFAIL(Label("line_valid")),
            JMP(Label("form_error")),
            Label("line_valid"),
            XOR(r2, r0),
            CMPI(r2, 0),
            MOV(r2, r0),
            JFAIL(Label("decoded_zero")),
            LDI(r0, 1),
            JMP(Label("decoded_bit")),
            Label("decoded_zero"),
            LDI(r0, 0),
            Label("decoded_bit"),
            CMPI(r3, 6),
            JFAIL(Label("data_bit")),
            JZ(r0, Label("stuff_ok")),
            JMP(Label("stuff_error")),
            Label("stuff_ok"),
            LDI(r3, 0),
            JMP(Label("next_raw")),
            Label("data_bit"),
            JZ(r0, Label("zero_bit")),
            ADDI(r3, 1),
            JMP(Label("append_bit")),
            Label("zero_bit"),
            LDI(r3, 0),
            Label("append_bit"),
            LDI(r1, 255),
            STORE(r0, r1),
            LDI(r1, 252),
            LOAD(r0, r1),
            ROR(r0),
            ANDI(r0, 127),
            LDI(r1, 255),
            LOAD(r1, r1),
            ROR(r1),
            OR(r0, r1),
            LDI(r1, 252),
            STORE(r0, r1),
            LDI(r1, 251),
            LOAD(r0, r1),
            ADDI(r0, 255),
            STORE(r0, r1),
            JZ(r0, Label("byte_full")),
            JMP(Label("next_raw")),
            Label("byte_full"),
            LDI(r1, 252),
            LOAD(r0, r1),
            LDI(r1, 253),
            LOAD(r1, r1),
            STORE(r0, r1),
            ADDI(r1, 1),
            MOV(r0, r1),
            LDI(r1, 253),
            STORE(r0, r1),
            LDI(r1, 251),
            LDI(r0, 8),
            STORE(r0, r1),
            Label("next_raw"),
            LDI(r1, 254),
            LOAD(r0, r1),
            ADDI(r0, 1),
            STORE(r0, r1),
            LDI(r1, 250),
            LOAD(r1, r1),
            XOR(r0, r1),
            JZ(r0, Label("packet_end")),
            JMP(Label("raw_bit")),
            Label("packet_end"),
            CMPI(r3, 6),
            JFAIL(Label("aligned")),
            JMP(Label("stuff_error")),
            Label("aligned"),
            LDI(r1, 251),
            LOAD(r0, r1),
            CMPI(r0, 8),
            JFAIL(Label("form_error")),
            LDI(r1, 253),
            LOAD(r0, r1),
            CMPLTI(r0, 147),
            JFAIL(Label("length_high")),
            JMP(Label("form_error")),
            Label("length_high"),
            CMPLTI(r0, 156),
            JFAIL(Label("overflow")),
            Comment(
                "Complementary PID halves, then DATA0 or DATA1 only in this probe."
            ),
            LDI(r1, 144),
            LOAD(r0, r1),
            MOV(r2, r0),
            SHR(r0),
            SHR(r0),
            SHR(r0),
            SHR(r0),
            XOR(r0, r2),
            ANDI(r0, 15),
            CMPI(r0, 15),
            JFAIL(Label("pid_error")),
            CMPI(r2, 0xC3),
            JFAIL(Label("maybe_data1")),
            JMP(Label("crc_begin")),
            Label("maybe_data1"),
            CMPI(r2, 0x4B),
            JFAIL(Label("unsupported")),
            Label("crc_begin"),
            LDI(r2, 255),
            LDI(r3, 255),
            LDI(r0, 145),
            LDI(r1, 254),
            STORE(r0, r1),
            Label("crc_byte"),
            LDI(r1, 254),
            LOAD(r1, r1),
            LOAD(r0, r1),
            XOR(r2, r0),
            LDI(r0, 8),
            LDI(r1, 251),
            STORE(r0, r1),
            Label("crc_bit"),
            MOV(r0, r2),
            ANDI(r0, 1),
            ROR(r3),
            MOV(r1, r3),
            ANDI(r1, 128),
            ANDI(r3, 127),
            SHR(r2),
            OR(r2, r1),
            JZ(r0, Label("crc_no_xor")),
            XORI(r2, 1),
            XORI(r3, 160),
            Label("crc_no_xor"),
            LDI(r1, 251),
            LOAD(r0, r1),
            ADDI(r0, 255),
            STORE(r0, r1),
            JZ(r0, Label("crc_next")),
            JMP(Label("crc_bit")),
            Label("crc_next"),
            LDI(r1, 254),
            LOAD(r0, r1),
            ADDI(r0, 1),
            STORE(r0, r1),
            LDI(r1, 253),
            LOAD(r1, r1),
            XOR(r0, r1),
            JZ(r0, Label("crc_done")),
            JMP(Label("crc_byte")),
            Label("crc_done"),
            CMPI(r2, 1),
            JFAIL(Label("crc_error")),
            CMPI(r3, 0xB0),
            JFAIL(Label("crc_error")),
            Comment(
                "Optional diagnostic ACK: measure this path, do not claim timely USB."
            ),
            LDI(r1, 0),
            LOAD(r0, r1),
            JZ(r0, Label("output")),
        ]
    )
    ack_states = [1, 2, 1, 2, 1, 2, 1, 1, 2, 2, 1, 2, 2, 1, 1, 1, 0, 0, 2]
    for index, state in enumerate(ack_states):
        out.add([SETO((32 + (state << 2)))])
        out.add(Fragment.delay(periods[index % 3] - 1))
    out.add(
        [
            SETO(56),
            Label("output"),
            LDI(r1, 253),
            LOAD(r2, r1),
            ADDI(r2, 112),
            MOV(r0, r2),
            LDI(r1, 134),
            STORE(r0, r1),
            LDI(r1, 144),
            Label("output_byte"),
            LOAD(r0, r1),
            LDI(r3, 0x30),
            PWRITE(r0, r3),
            LDI(r0, 0),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r3, 1),
            PWRITE(r0, r3),
            ADDI(r1, 1),
            DJNZ(r2, Label("output_byte")),
            JMP(Label("publish")),
            Label("timeout"),
            LDI(r2, 6),
            JMP(Label("failure")),
            Label("crc_error"),
            LDI(r2, 16),
            JMP(Label("failure")),
            Label("form_error"),
            LDI(r2, 17),
            JMP(Label("failure")),
            Label("unsupported"),
            LDI(r2, 18),
            JMP(Label("failure")),
            Label("stuff_error"),
            LDI(r2, 19),
            JMP(Label("failure")),
            Label("overflow"),
            LDI(r2, 20),
            JMP(Label("failure")),
            Label("pid_error"),
            LDI(r2, 21),
            Label("failure"),
        ]
    )
    out.add(footer)
    return out.program


if __name__ == "__main__":
    Path(__file__).with_name("usb_rx_candidate.asm").write_text(generate().to_asm())
