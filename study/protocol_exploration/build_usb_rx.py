#!/usr/bin/env python3
"""Low-speed USB packet capture/validation and ACK-latency experiment.

No USB engine or instruction is added. This packet probe is deliberately not
an enumerating USB device: its buffered decode/CRC path must be measured before
it can be used for transaction responses.
"""

from pathlib import Path

from build_can_rx import Block
from build_can_rx import generate as request_template


def generate():
    # Share the known request/event ABI source, without changing its baseline.
    source = request_template()
    prefix = source.split("LDI r1, 242\n", 1)[0]
    prefix = prefix.replace("SETO 1\nSETOE 1", "SETO 56\nSETOE 60")
    footer = source.split("\nfailure:\n", 1)[1].replace("SETO 1\n", "SETO 56\n")
    out = Block("""
    # GENERATED by build_usb_rx.py. Packet experiment; NOT a USB device.
    # TUSB1106: uio0=VP,1=VM,2=VPO,3=VMO,4=OE_n,5=SOFTCON.
    # SPEED/SUSPND strapped low. No analog pads or protocol-aware RTL.
    # param[0]=0 passive,1 emit diagnostic ACK after buffered validation.
    # Event128..143; raw states144..249 then bytes144..154; state250..255.
    """)
    # Drop inherited receive-only comments; retain the request handling.
    out.add("\n".join(line for line in prefix.splitlines() if not line.startswith("#")))
    out.add("""
    LDI r2, 0
    LDI r3, 0
wait_idle:
    IN r0
    ANDI r0, 3
    CMPI r0, 2
    JFAIL idle_tick
    JMP wait_sop
idle_tick:
    DJNZ r3, wait_idle
    DJNZ r2, wait_idle
    JMP timeout
wait_sop:
    IN r0
    ANDI r0, 3
    CMPI r0, 1
    JFAIL sop_tick
    LDI r1, 144
    WAIT 10
    """)
    periods = [33, 33, 34]
    for index, expected in enumerate([1, 2, 1, 2, 1, 2, 1, 1]):
        out.add(
            f"sync_{index}:\nIN r0\nANDI r0, 3\nCMPI r0, {expected}\nJFAIL form_error"
        )
        out.add(Block.delay(periods[index % 3] - 4 - (1 if index == 7 else 0)))
    out.add("JMP capture_0")
    out.add("sop_tick:\nDJNZ r3, wait_sop\nDJNZ r2, wait_sop\nJMP timeout")
    # Next global bit index8 has the34-clock phase. Capture to RAM is fast;
    # NRZI, destuffing and CRC are initially measured as buffered software.
    capture_periods = [34, 33, 33]
    for index, period in enumerate(capture_periods):
        out.add(f"""
capture_{index}:
    IN r0
    ANDI r0, 3
    STORE r0, r1
    ADDI r1, 1
    JZ r0, eop_{index}
    CMPI r1, 250
    JFAIL room_{index}
    JMP overflow
room_{index}:
    """)
        out.add(Block.delay(period - 8 - 1)).add(f"JMP capture_{(index + 1) % 3}")
    for index, period in enumerate(capture_periods):
        out.add(f"""
eop_{index}:
    MOV r0, r1
    ADDI r0, 255
    LDI r1, 250
    STORE r0, r1
    """)
        out.add(Block.delay(period - 11))
        out.add("IN r0\nANDI r0, 3\nCMPI r0, 0\nJFAIL form_error")
        out.add(Block.delay(capture_periods[(index + 1) % 3] - 4))
        out.add("IN r0\nANDI r0, 3\nCMPI r0, 2\nJFAIL form_error\nJMP decode")
    out.add("""
decode:
    LDI r1, 250
    LOAD r0, r1
    CMPI r0, 144
    JFAIL decode_nonempty
    JMP form_error
decode_nonempty:
    # State250=exclusive raw end,251=bits left,252=byte,253=byte write ptr,
    # 254=raw read ptr,255=decoded bit. Decode behind the raw read cursor.
    LDI r0, 8
    LDI r1, 251
    STORE r0, r1
    ADDI r1, 1
    LDI r0, 0
    STORE r0, r1
    ADDI r1, 1
    LDI r0, 144
    STORE r0, r1
    ADDI r1, 1
    STORE r0, r1
    LDI r2, 1
    LDI r3, 1
raw_bit:
    LDI r1, 254
    LOAD r1, r1
    LOAD r0, r1
    CMPI r0, 3
    JFAIL line_valid
    JMP form_error
line_valid:
    XOR r2, r0
    CMPI r2, 0
    MOV r2, r0
    JFAIL decoded_zero
    LDI r0, 1
    JMP decoded_bit
decoded_zero:
    LDI r0, 0
decoded_bit:
    CMPI r3, 6
    JFAIL data_bit
    JZ r0, stuff_ok
    JMP stuff_error
stuff_ok:
    LDI r3, 0
    JMP next_raw
data_bit:
    JZ r0, zero_bit
    ADDI r3, 1
    JMP append_bit
zero_bit:
    LDI r3, 0
append_bit:
    LDI r1, 255
    STORE r0, r1
    LDI r1, 252
    LOAD r0, r1
    ROR r0
    ANDI r0, 127
    LDI r1, 255
    LOAD r1, r1
    ROR r1
    OR r0, r1
    LDI r1, 252
    STORE r0, r1
    LDI r1, 251
    LOAD r0, r1
    ADDI r0, 255
    STORE r0, r1
    JZ r0, byte_full
    JMP next_raw
byte_full:
    LDI r1, 252
    LOAD r0, r1
    LDI r1, 253
    LOAD r1, r1
    STORE r0, r1
    ADDI r1, 1
    MOV r0, r1
    LDI r1, 253
    STORE r0, r1
    LDI r1, 251
    LDI r0, 8
    STORE r0, r1
next_raw:
    LDI r1, 254
    LOAD r0, r1
    ADDI r0, 1
    STORE r0, r1
    LDI r1, 250
    LOAD r1, r1
    XOR r0, r1
    JZ r0, packet_end
    JMP raw_bit
packet_end:
    CMPI r3, 6
    JFAIL aligned
    JMP stuff_error
aligned:
    LDI r1, 251
    LOAD r0, r1
    CMPI r0, 8
    JFAIL form_error
    LDI r1, 253
    LOAD r0, r1
    CMPLTI r0, 147
    JFAIL length_high
    JMP form_error
length_high:
    CMPLTI r0, 156
    JFAIL overflow
    # Complementary PID halves, then DATA0 or DATA1 only in this probe.
    LDI r1, 144
    LOAD r0, r1
    MOV r2, r0
    SHR r0
    SHR r0
    SHR r0
    SHR r0
    XOR r0, r2
    ANDI r0, 15
    CMPI r0, 15
    JFAIL pid_error
    CMPI r2, 0xc3
    JFAIL maybe_data1
    JMP crc_begin
maybe_data1:
    CMPI r2, 0x4b
    JFAIL unsupported
crc_begin:
    LDI r2, 255
    LDI r3, 255
    LDI r0, 145
    LDI r1, 254
    STORE r0, r1
crc_byte:
    LDI r1, 254
    LOAD r1, r1
    LOAD r0, r1
    XOR r2, r0
    LDI r0, 8
    LDI r1, 251
    STORE r0, r1
crc_bit:
    MOV r0, r2
    ANDI r0, 1
    ROR r3
    MOV r1, r3
    ANDI r1, 128
    ANDI r3, 127
    SHR r2
    OR r2, r1
    JZ r0, crc_no_xor
    XORI r2, 1
    XORI r3, 160
crc_no_xor:
    LDI r1, 251
    LOAD r0, r1
    ADDI r0, 255
    STORE r0, r1
    JZ r0, crc_next
    JMP crc_bit
crc_next:
    LDI r1, 254
    LOAD r0, r1
    ADDI r0, 1
    STORE r0, r1
    LDI r1, 253
    LOAD r1, r1
    XOR r0, r1
    JZ r0, crc_done
    JMP crc_byte
crc_done:
    CMPI r2, 1
    JFAIL crc_error
    CMPI r3, 0xb0
    JFAIL crc_error
    # Optional diagnostic ACK: measure this path, do not claim timely USB.
    LDI r1, 0
    LOAD r0, r1
    JZ r0, output
    """)
    ack_states = [1, 2, 1, 2, 1, 2, 1, 1, 2, 2, 1, 2, 2, 1, 1, 1, 0, 0, 2]
    for index, state in enumerate(ack_states):
        out.add(f"SETO {32 + (state << 2)}")
        out.add(Block.delay(periods[index % 3] - 1))
    out.add("""
    SETO 56
output:
    LDI r1, 253
    LOAD r2, r1
    ADDI r2, 112
    MOV r0, r2
    LDI r1, 134
    STORE r0, r1
    LDI r1, 144
output_byte:
    LOAD r0, r1
    LDI r3, 0x30
    PWRITE r0, r3
    LDI r0, 0
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r3, 1
    PWRITE r0, r3
    ADDI r1, 1
    DJNZ r2, output_byte
    JMP publish
timeout:
    LDI r2, 6
    JMP failure
crc_error:
    LDI r2, 16
    JMP failure
form_error:
    LDI r2, 17
    JMP failure
unsupported:
    LDI r2, 18
    JMP failure
stuff_error:
    LDI r2, 19
    JMP failure
overflow:
    LDI r2, 20
    JMP failure
pid_error:
    LDI r2, 21
failure:
    """)
    out.add(footer)
    return "\n".join(out.lines) + "\n"


if __name__ == "__main__":
    Path(__file__).with_name("usb_rx_candidate.asm").write_text(generate())
