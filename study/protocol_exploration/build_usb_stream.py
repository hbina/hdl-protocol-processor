#!/usr/bin/env python3
"""Live generic-instruction USB TX; no payload CRC/waveform precomputation."""

from pathlib import Path

from build_can_rx import Block
from build_usb_in import generate as packet_source


def crc_seed(pid):
    # Reverse eight CRC steps so including PID leaves the normal0xffff seed
    # at the first payload bit. These are PID constants, not payload FCS.
    value = 0xFFFF
    for bit in range(7, -1, -1):
        old_low = value >> 15
        value = (((value ^ (0xA001 if old_low else 0)) << 1) | old_low) & 0xFFFF
        value ^= (pid >> bit) & 1
    return value


def generate():
    source = packet_source().split("prepare_tx:\n", 1)[0]
    out = Block(source)
    out.add("""
prepare_tx:
LDI r0, 182
LOAD r6, r0
CMPLTI r6, 9
JFAIL form_error
LDI r0, 39
LOAD r4, r0
CMPI r4, 0xc3
JFAIL stream_data1
JMP stream_pid_ok
stream_data1:
CMPI r4, 0x4b
JFAIL pid_error
stream_pid_ok:
LDI r7, 160
STORE r4, r7
JZ r6, rearm
stream_payload:
LDI r0, 0x11
PREAD r4, r0
ADDI r7, 1
STORE r4, r7
DJNZ r6, stream_payload
JMP rearm
tx_packet:
LDI r0, 185
LDI r1, 1
STORE r1, r0
LDI r0, 182
LOAD r6, r0
ADDI r6, 3
LDI r7, 160
LOAD r1, r7
LDI r5, 8
LDI r4, 1
LDI r0, 36
CMPI r1, 0xc3
JFAIL stream_seed1
""")
    seed0, seed1 = crc_seed(0xC3), crc_seed(0x4B)
    out.add(
        f"LDI r2, {seed0 & 255}\nLDI r3, {seed0 >> 8}\nJMP stream_sync\nstream_seed1:\nLDI r2, {seed1 & 255}\nLDI r3, {seed1 >> 8}\nstream_sync:\nWAIT 20"
    )
    # SYNC has seven zero bits and one one. It ends K, with one trailing1.
    for index, line in enumerate([36, 40, 36, 40, 36, 40, 36, 36]):
        out.add(f"SETO {line}")
        period = [33, 33, 34][index % 3]
        if index < 7:
            out.add(Block.delay(period - 1))
        else:
            out.add("CALL stream_bit").add(Block.delay(period - 17)).add(
                "JMP stream_cell_2"
            )
    for phase, period in enumerate([33, 33, 34]):
        following = (phase + 1) % 3
        out.add(f"""
stream_cell_{phase}:
OUT r0
CMPI r4, 6
JFAIL stream_advance_{phase}
XORI r0, 12
LDI r4, 0
""")
        out.add(Block.delay(period - 6)).add(f"JMP stream_stuff_{following}")
        out.add(f"stream_stuff_{phase}:\nOUT r0\nNOP\nJMP stream_advance_{phase}")
        out.add(f"""
stream_advance_{phase}:
DJNZ r5, stream_same_{phase}
DJNZ r6, stream_new_{phase}
""")
        # Last logical bit (and any mandatory final stuff) precedes EOP.
        out.add(Block.delay(period - 5)).add("SETO 32")
        out.add(Block.delay([33, 33, 34][following] - 1)).add("SETO 32")
        out.add(Block.delay([33, 33, 34][(phase + 2) % 3] - 1)).add("SETO 40")
        out.add(Block.delay(period - 1)).add("SETO 56\nJMP rearm")
        out.add(f"""
stream_new_{phase}:
ADDI r7, 1
LDI r5, 8
CMPI r6, 2
JFAIL stream_maybe_high_{phase}
MOV r1, r2
XORI r1, 255
CALL stream_bit
""")
        out.add(Block.delay(period - 27)).add(f"JMP stream_cell_{following}")
        out.add(f"""
stream_maybe_high_{phase}:
CMPI r6, 1
JFAIL stream_load_{phase}
MOV r1, r3
XORI r1, 255
CALL stream_bit
""")
        out.add(Block.delay(period - 29)).add(f"JMP stream_cell_{following}")
        out.add(f"stream_load_{phase}:\nLOAD r1, r7\nCALL stream_bit")
        out.add(Block.delay(period - 29)).add(f"JMP stream_cell_{following}")
        out.add(f"stream_same_{phase}:\nCALL stream_bit")
        out.add(Block.delay(period - 20)).add(f"JMP stream_cell_{following}")
    out.add("stream_bit:\nSHRC r1")
    out.add(Block.choose("JNC", "XORI r0, 12\nLDI r4, 0", "ADDI r4, 1\nXORI r2, 1"))
    crc = Block("SHRC r3\nRRC r2").add(
        Block.choose("JNC", "", "XORI r2, 1\nXORI r3, 160")
    )
    out.add("CMPLTI r6, 3").add(Block.choose("JFAIL", crc, "")).add("RET")
    result = "\n".join(out.lines) + "\n"
    return result.replace(
        "# GENERATED by build_usb_in.py.", "# GENERATED by build_usb_stream.py."
    )


if __name__ == "__main__":
    Path(__file__).with_name("usb_stream_candidate.asm").write_text(generate())
